
CREATE PROCEDURE APZ_KPIPlan_Search(
   in docEntry INT
,  in fromDate timestamp default ''
,  in toDate timestamp default ''
,  in active NVARCHAR(20) default '')
AS
BEGIN
	-- Khai báo bảng dữ liệu combobox (tùy chọn)
	DECLARE tblValidValue TABLE (
		"ColumnName" NVARCHAR(50) NOT NULL
		,"Value" NVARCHAR(254) NOT NULL
		,"Description" NVARCHAR(254) NOT NULL
		,"BackColor" NVARCHAR(20)
		,"ForeColor" NVARCHAR(20)
	);
	INSERT INTO :tblValidValue ("ColumnName", "Value", "Description")
		select N'PeriodType',N'D' ,		N'Daily' from DUMMY
			UNION ALL
		select N'PeriodType',N'W' ,		N'Weekly' from DUMMY
			UNION ALL
		select N'PeriodType',N'M' ,		N'Monthly' from DUMMY
			UNION ALL
		select N'PeriodType',N'Q' ,		N'Quarterly' from DUMMY
			UNION ALL
		select N'PeriodType',N'Y' ,		N'Yearly' from DUMMY
			UNION ALL
		select N'Active',N'Y' ,		N'Yes' from DUMMY
			UNION ALL
		select N'Active',N'N' ,		N'No' from DUMMY
			UNION ALL
		select N'Type',	N'1' ,		N'Doanh thu' from DUMMY
			UNION ALL
		select N'Type',	N'2' ,		N'Số lượng' from DUMMY
			UNION ALL
		select N'Type',	N'3' ,		N'Số lượng KH mới' from DUMMY
			UNION ALL
		select N'Type',	N'4' ,		N'Số lượng hợp đồng' from DUMMY;

	-- Khai báo bảng Structure
	create local temporary table #tblStructure(
        ID INT generated by default as identity
        ,"ColumnName" NVARCHAR(50) PRIMARY KEY
        ,"Caption" NVARCHAR(100)
        ,"DataType" VARCHAR(50) DEFAULT 'nvarchar' --int decimal money datetime date/ numeric alpha Memo(general) Numeric Date float(unit)  ValidValue(combobox) LinkedTable LinkedUDO* LinkedObject cfl(choosefromlist) LinkedCflObject
                                                -- color, validcolor (combobox+color),	linkedStore, LinkedCrystal
		,"SubType" VARCHAR(100)	-- None Phone Percentage Address Image Measurement Price Quantity Rate Sum Time, UDT dùng cho LinkedTable, (udo code : dùng cho LinkedUDO)*	 , ObjectType(số): dùng cho LinkedObject
                                    -- type of cfl - số của type hoặc tên store(storename @value, @userName, @branch) lấy dữ liệu cfl-store phải có structure, sub - sub form
        ,"Width" INT DEFAULT 75
        ,"GroupIndex" INT DEFAULT -1	-- dùng cho grid  default -1
        ,"Visible" tinyint DEFAULT 1
        ,"FormatType" NVARCHAR(20)   -- numeric, datetime/ 
        ,"DisplayFormat" NVARCHAR(20) NULL  -- '{0:n2}'
        ,"ReadOnly" tinyint DEFAULT 0
        ,"AllowEdit" tinyint DEFAULT 1
        ,"AllowMove" tinyint DEFAULT 1
        ,"AllowSize" tinyint DEFAULT 1
        ,"AllowSort" tinyint DEFAULT 1
        ,"Fixed" VARCHAR(1)	-- L:Left / R:Right
		,"BackColor" NVARCHAR(20) -- color column //list color https://msdn.microsoft.com/en-us/library/aa358802(v=vs.85).aspx
        ,"ForeColor" NVARCHAR(20)
        -- Summary Item
        ,"SummaryType" VARCHAR(10)	-- sum,average...
        ,"GroupSummaryType" VARCHAR(10)	-- sum,average...
        ,"GroupSummaryShowInFooter" tinyint
        ,"SummaryFormat" NVARCHAR(50) -- (AVR={0:#.##})/ Count ({0})/ Custom format/ Max (MAX={0})/ Min (MIN={0})/ Sum (SUM={0:#.##})
        ,"Expression" NVARCHAR(5000)
		,"Parent" tinyint	-- dùng cho treelist
		,"Key" tinyint		-- dùng cho treelist (identity)
		,"PivotArea" NVARCHAR(20)		-- dùng cho pivot grid
    );

     INSERT INTO #tblStructure 
					("ColumnName",		"Caption",				"DataType",	"SubType",	"Width",	"GroupIndex", "Visible",	"FormatType", "DisplayFormat",		"ReadOnly", "AllowEdit", "AllowMove", "AllowSize", "AllowSort", "Fixed", "SummaryType", "GroupSummaryType", "BackColor")
	    select N'DocEntry',	N'DocEntry',	'int',			'',		75,			-1,			0,			NULL,		NULL,				1,		 1,			1,			1,			0,		 'L',	NULL,		 NULL,		 'silver' from DUMMY
	    	UNION ALL
		select N'Name',		N'Name',		'nvarchar',		'',		200,		-1,			1,			NULL,		NULL,				0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'PeriodType',N'Period Type',	'ValidValue',	'',		100,		-1,			1,			NULL,		NULL,				0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'StartDate',	N'Start Date',	'datetime',		'',		75,			-1,			1,			NULL,		NULL,				0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'EndDate',	N'End Date',	'datetime',		'',		75,			-1,			1,			NULL,		NULL,				0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'Type',		N'Type',		'ValidValue',	'',		100,		-1,			1,			NULL,		NULL,				0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'Active',	N'Active',		'ValidValue',	'',		75,			-1,			1,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'Remark',	N'Remark',		'nvarchar',		'',		150,		-1,			1,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'UserSign',	N'UserSign',	'nvarchar',		'',		75,			-1,			0,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'CreateDate',N'CreateDate',	'datetime',		'',		75,			-1,			0,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'UserSign2',	N'UserSign2',	'nvarchar',		'',		75,			-1,			0,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL from DUMMY
	    	UNION ALL
		select N'UpdateDate',N'UpdateDate',	'datetime',		'',		75,			-1,			0,			'',			'',					0,		 1,			1,			1,			0,		 '',	NULL,		 NULL,		 NULL FROM DUMMY;
					
		SELECT *
			FROM #tblStructure ORDER BY ID;
		
	SELECT * FROM APZ_OKPN
		WHERE (:docEntry= 0 OR (:docEntry <> 0 AND "DocEntry" = :docEntry))
			AND( :fromDate = '' OR (cast("CreateDate" as date) BETWEEN :fromDate AND :toDate))
			AND (:active= N'' OR (:active <> N'') AND "Active" = :active);

	SELECT * FROM :tblValidValue;
END






