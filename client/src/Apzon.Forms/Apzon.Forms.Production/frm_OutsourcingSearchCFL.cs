	private void frm_OutsourcingSearchCFL_Load(object sender, EventArgs e)
	{
		try
		{
			grd_Doc.DataSource = DTSource;
			grd_Doc.RefreshDataSource();
		}
		catch (Exception ex)
		{
			Logging.Write("ERROR", new StackTrace(new StackFrame(0)).ToString().Substring(5, new StackTrace(new StackFrame(0)).ToString().Length - 5), ex.Message);
			WinCommons.Error(Enums.MessageCode.ExceptionMessage, ex.Message);
		}
	}

	private void grd_Doc_DoubleClick(object sender, EventArgs e)
	{
		ChooseRow();
	}

	private void ChooseRow()
	{
		try
		{
			if (DTSource != null && DTSource.Rows.Count > 0)
			{
				ChoosenRow = DTSource.Rows[gv_Doc.GetFocusedDataSourceRowIndex()];
			}
		}
		catch (Exception ex)
		{
			Logging.Write("ERROR", new StackTrace(new StackFrame(0)).ToString().Substring(5, new StackTrace(new StackFrame(0)).ToString().Length - 5), ex.Message);
			WinCommons.Error(Enums.MessageCode.ExceptionMessage, ex.Message);
		}
		Close();
	}

	protected override void Dispose(bool disposing)
