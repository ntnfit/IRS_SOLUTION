CREATE procedure ILD_R_IRS_Costing_StandardCost
(
	in FromDate date,
	in ToDate date
)
as
BEGIN
 		select WOID,WONO,DOCENTRY,cast(DOCNUM as nvarchar) as DOCNUM,SYSTEMDATE,POSTINGDATE,FGCODE,FGNAME,PLANFGQTY,CMPLTQTY,UNITPRICEFG,AMOUNTFG,ITEMCODE,ITEMNAME,BOMRATE,STDQTY,UNITPRICE,STDAMOUNT,ITMSGRPCOD,ITMSGRPNAME,CUMULATIVE_QTY,CUMULATIVE_VALUE,WAREHOUSE,LINENUM,SYSTEMDATE_USECOMPARE,POSTINGDATE_USECOMPARE,SYSTEMDATE_TIME,
					POSTINGDATE_TIME,PLAN_MATERIALS_QTY,ISSUEDQTY,ISSUETYPE,DISID,DISNO,U_GROUP
		from COSTING_STANDARDCOST where  POSTINGDATE between Fromdate and Todate order by  WOID, LineNum;
END;
