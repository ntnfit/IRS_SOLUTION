CREATE procedure USP_RPT_INVNT_03_Bkup( --16_05_2024
	in fdate			timestamp,
	in tdate			timestamp,
	in groupID			int,
	in warehouse		nvarchar(20),
	in account			nvarchar(20),
	in itemcode			nvarchar(5000),
	in cancel			int
)
as
begin
	-- CHI TIẾT NHẬP XUẤT TỒN----------------------------------------------------------------------------------------------
	create local temporary table #tbl (
		ID				int not null primary key generated by default as IDENTITY,
		Pos				int,
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		DocType			nvarchar(20),
		AppObj			nvarchar(10),
		DocNote			nvarchar(50),
		DocID			int,
		DocDate			timestamp,
		Comments		nvarchar(300),
		Warehouse		nvarchar(20), 
		INQty			numeric(21,6),
		INAmt			numeric(21,6),
		OUQty			numeric(21,6),
		OUAmt			numeric(21,6),
		BalQty			numeric(21,6),
		BalAmt			numeric(21,6),
		Note			nvarchar(100),
		DocTime 		varchar(10),
		DocNum			nvarchar(50),
		InQtyPre		numeric(21,6),
		OuQtyPre		numeric(21,6)
	);
	-------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblWH (
		WHCode			nvarchar(20),
		WHName			nvarchar(100),
		WHAccount		nvarchar(20)
	);
	insert into #tblWH (WHCode,WHName,WHAccount) select "WhsCode","WhsName","BalInvntAc" from "OWHS" 
	where 
		--(branch in (-1,0) or "BPLid"=branch) and 
		(warehouse='' or "WhsCode"=warehouse);
	------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblITEM (
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		UoM				nvarchar(50),
		InventoryAcct	nvarchar(20),
		GLMethod		char(1),
		GrpID			int,
		GrpName			nvarchar(100)
	);
	insert into #tblITEM (ItemCode,ItemName,UoM,GrpID,GrpName,GLMethod,InventoryAcct) 
	select a."ItemCode",a."ItemName",a."InvntryUom",b."ItmsGrpCod",b."ItmsGrpNam",a."GLMethod",case when a."GLMethod"='C' then b."BalInvntAc" end
	from "OITM" a, "OITB" b 
	where a."ItmsGrpCod"=b."ItmsGrpCod" and a."InvntItem"='Y'
	and (b."ItmsGrpCod"=groupID or groupID=0)
	and
			(
			IFNULL(:itemcode, '') = '' OR cast ("ItemCode" as nvarchar) IN (SELECT "DATA" FROM "SPLIT"(:itemcode, ','))
			--ifnull((select STRING_AGG( Code) from :itemcode), '') = '' OR cast (a."ItemCode" as nvarchar) IN (select Code from :itemcode)
			) 
	;
	--------------------------------------------------------------------------------------------------------------------------
	--RAW DATA ---------------------------------------------------------------------------------------------------------------
	create local temporary table #tblDATA (
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		TransNum		int,
		DocType			nvarchar(20),
		AppObj			nvarchar(10),
		DocID			int,
		DocDate			timestamp,
		Comments		nvarchar(300),
		Warehouse		nvarchar(20), 
		InQty			numeric(21,6),
		InQtyPre		numeric(21,6),
		OuQty			numeric(21,6),
		OuQtyPre		numeric(21,6),
		Amount			numeric(21,6)
	);
	insert into #tblDATA (GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse,InQty,OuQty,Amount,DocDate,DocType,AppObj,DocID,Comments,TransNum,
	InQtyPre,OuQtyPre
	)
	select c.GrpID,c.GrpName,c.ItemCode,c.ItemName,c.UoM,b.WHCode
	,(
		 CASE when a."TransType" in ('14','16','18','20','69','162') then (IFNULL(a."InQty",0)-IFNULL(a."OutQty",0))
						else 
							CASE when a."TransType" not in ('13','15','19','21') then a."InQty" end 
						end
	
	)
	,(
		 CASE when a."TransType" in ('13','15','19','21') then -IFNULL(a."InQty",0)+IFNULL(a."OutQty",0) 
						else 
							CASE when a."TransType" not in ('14','16','18','20','69','162') then a."OutQty" end 
						end
	)
	,a."TransValue",a."DocDate",a."TransType",a."ApplObj",a."CreatedBy",a."Comments",a."TransNum"
	,IFNULL(a."InQty",0)-IFNULL(a."OutQty",0)
	,-IFNULL(a."InQty",0)+IFNULL(a."OutQty",0)
	from "OINM" a, #tblWH b, #tblITEM c--, APZ_ODOC d
	where a."DocDate"<=tdate and a."Warehouse"=b.WHCode and a."ItemCode"=c.ItemCode  --and a."TransType" = d."ObjType"
	--and a."CreatedBy" = d."DocEntry" 
	--and ( :cancel = 2 or  ifnull(d."CANCELED", 'N') = 'N')  
	and (account='' 
		or (ifnull(a."InvntAct",'')<>'' and a."InvntAct"=account) 
		or (ifnull(a."InvntAct",'')='' and c.GLMethod='C' and c.InventoryAcct=account)
		or (ifnull(a."InvntAct",'')='' and c.GLMethod='W' and b.WHAccount=account)
	);

	create local temporary table #tblBALANCE (
		ItemCode		nvarchar(50),
		Qty				numeric(21,6),
		Amount			numeric(21,6)
	);
	-- REPORT ----------------------------------------------------------------------------------------------------------------
	-- Số dư đầu kỳ -------------------------
	
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,BalQty,BalAmt,Comments)
	
	select 1,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,
		sum(InQtyPre),sum(Amount),
		'Số dư đầu kỳ'
	from #tblDATA
	where DocDate<fdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;

	insert into #tblBALANCE (ItemCode,Qty,Amount) select ItemCode,BalQty,BalAmt from #tbl;	
	-- Chi tiết phát sinh trong kỳ
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse,InQty,InAmt,OuQty,OuAmt,Comments,DocType,AppObj,DocID,DocDate,BalQty,BalAmt,InQtyPre,OuQtyPre)
	select 2,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse,InQty,case when Amount>0 then Amount else 0 end,OuQty,case when Amount>0 then 0 else -Amount end,Comments,DocType,AppObj,DocID,DocDate,
		ifnull(sum(InQtyPre) OVER (Partition by ItemCode order by DocDate,TransNum),0) + ifnull((select x.Qty from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		ifnull(sum(Amount) OVER (Partition by ItemCode order by DocDate,TransNum),0) + ifnull((select x.Amount from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0)
		,InQtyPre,OuQtyPre
	from #tblDATA
	where DocDate between fdate and tdate
	order by ItemCode,DocDate,TransNum
	;
	
	-- update InAmt = - OuAmt nếu phiếu cancel bên nhập < 0  có giá trị bên xuất dương
	update x set InAmt  = - OuAmt from #tbl x where InQty < 0  and ifnull(OuQty,0) = 0;
	update x set OuAmt = null from #tbl x where InQty < 0  and ifnull(OuQty,0) = 0;
	-- Tổng phát sinh trong kỳ -------------------------
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,InQty,InAmt,OuQty,OuAmt,Comments,BalQty,BalAmt,InQtyPre,OuQtyPre)
	select 3,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,sum(InQty),sum(case when Amount>0 then Amount else 0 end),sum(OuQty),sum(case when Amount>0 then 0 else -Amount end),'Tổng phát sinh trong kỳ',
		ifnull(sum(InQtyPre),0) + ifnull((select x.Qty from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		ifnull(sum(Amount),0) + ifnull((select x.Amount from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		sum(InQtyPre),sum(OuQtyPre)
	from #tblDATA
	where DocDate between fdate and tdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;
	
	-- update lại tổng phát sinh
	update x set InAmt = (select sum(InAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	update x set OuAmt = (select sum(OuAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	--update x set BalAmt = (select sum(BalAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	
	
	
	-- Số dư cuối kỳ -------------------------
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,BalQty,BalAmt,Comments)
	select 4,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,
		sum(InQtyPre),sum(Amount),'Số dư cuối kỳ'
	from #tblDATA
	where DocDate<=tdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;
	
	Update a
	set DocTime = (case     when LENGTH(b."DocTime")  = 1 then  '00:0'|| b."DocTime"
							 when LENGTH(b."DocTime")  = 2 then  '00:'|| b."DocTime"				
							 when LENGTH(b."DocTime")  = 3 then  '0'||left(b."DocTime",1) || ':' || right(b."DocTime",2) 
		 					 when LENGTH(b."DocTime")  = 4 then   left(b."DocTime",2) || ':' || right(b."DocTime",2)  
	 			else  '' end  ),
	 	DocNum = b."BASE_REF"
	 			
	from #tbl a
	left join  OINM b on a.DOCID =b."CreatedBy" and a.DOCTYPE  = b."TransType";
	
	
	
	
	update #tbl set DocNote = 'A/R Invoice' where DocType='13';
	update #tbl set DocNote = 'A/R Credit Memo' where DocType='14';
	update #tbl set DocNote = 'Delivery' where DocType='15';
	update #tbl set DocNote = 'Return' where DocType='16';
	update #tbl set DocNote = 'A/P Invoice' where DocType='18';
	update #tbl set DocNote = 'A/P Credit Memo' where DocType='19';
	update #tbl set DocNote = 'Goods Receipt PO' where DocType='20';
	update #tbl set DocNote = 'Goods Return' where DocType='21';
	update #tbl set DocNote = 'Goods Receipt' where DocType='59' and AppObj='-1';
	update #tbl set DocNote = 'Receipt from Production' where DocType='59' and AppObj='202';
	update #tbl set DocNote = 'Goods Issue' where DocType='60' and AppObj='-1';
	update #tbl set DocNote = 'Issue for Production' where DocType='60' and AppObj='202';
	update #tbl set DocNote = 'Inventory Transfer' where DocType='67';
	update #tbl set DocNote = 'Landed Costs' where DocType='69';
	update #tbl set DocNote = 'Revaluation' where DocType='162';
	------------
	


	
	select * from #tbl a order by ItemCode,Pos,ID,DocDate,DocTime;
	--ItemCode,Pos,ID;

	drop table #tbl;
	drop table #tblWH;
	drop table #tblITEM;
	drop table #tblDATA;
	drop table #tblBALANCE;
end

