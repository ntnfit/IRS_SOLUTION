	protected override void SetFormMode(Enums.FormViewModeType value)
	{
		_formMode = value;
		if (FormAuth != Enums.FormAuthorities.Full && FormAuth != Enums.FormAuthorities.Edit)
		{
			btn_Functions.Enabled = false;
			btn_Cancel.Enabled = true;
			return;
		}
		switch (value)
		{
		case Enums.FormViewModeType.Update:
			btn_Functions.Text = Apzon.Commons.Properties.Resources.ButtonUpdate;
			break;
		case Enums.FormViewModeType.View:
			btn_Functions.Text = Apzon.Commons.Properties.Resources.ButtonOK;
			break;
		}
	}

	public frm_AdditionalGeneralSettings()
	{
		if (GlobalData.ListAccessForm.Exists((AuthsImpl x) => x.menucode == "frm_AdditionalGeneralSettings"))
		{
			InitializeComponent();
			if (!GlobalData.ListAccessForm.Exists((AuthsImpl x) => x.menucode == "frm_AdditionalGeneralSettings" && x.authoriza == "F"))
			{
				WinFuntions.DisableAllControl(Controls);
				cms_RightMenu.Enabled = false;
				btn_Cancel.Enabled = true;
			}
			OnLoadAsync += frm_AdditionalGeneralSettings_Load;
			return;
		}
		throw new Exception(Apzon.Commons.Properties.Resources.Msg_FormAccessDenied);
	}

	public async Task LoadData()
	{
		try
		{
			LoadApzObjectType();
			CheckLocationSetting();
			look_AuthorizationMode.SetDataSource(new Dictionary<string, string>
			{
				{ "R", "Route" },
				{ "O", "Owner" }
			});
			look_warehouseInventoryType.SetDataSource(new Dictionary<string, string>
			{
				{ "O", "Items have been ordered" },
				{ "A", "All active items" },
				{ "G", "All item groups" }
			});
			_ds = await _httpClient.AdditionalGeneralSettingsClient.GetData();
			if (_ds.Tables[0].IsNotNull())
			{
				if (string.IsNullOrEmpty(Function.ToString(_ds.Tables[0].Rows[0]["DflLng"])))
				{
					_ds.Tables[0].Rows[0]["DflLng"] = "en-US";
				}
				if (string.IsNullOrEmpty(Function.ToString(_ds.Tables[0].Rows[0][rd_ORM.FieldName])))
				{
					_ds.Tables[0].Rows[0][rd_ORM.FieldName] = "U";
				}
				_ds.Tables[0].AcceptChanges();
				DataSource = _ds.Tables[0];
			}
			else
			{
				DataTable dataTable = _ds.Tables[0].Clone();
				DataRow dataRow = dataTable.NewRow();
				dataRow[chk_AutoGenerateDocument.FieldName] = "N";
				dataRow[chk_DisableSplitFolder.FieldName] = "N";
				dataRow["CheckPromotion"] = "N";
				dataRow[rd_ORM.FieldName] = "U";
				dataRow["DflLng"] = "en-US";
				dataTable.Rows.Add(dataRow);
				dataTable.AcceptChanges();
				DataSource = dataTable;
			}
			gc_Path.DataSource = _ds.Tables[1];
			if (_ds.Tables.Count > 2)
			{
				DataTable dataTable2 = _ds.Tables[2];
				if (dataTable2.IsNotNull())
				{
					txt_UploadServer.EditValue = Function.ToString(dataTable2.Rows[0]["UploadServer"]);
					txt_uploadSecrecyApp.EditValue = Function.ToString(dataTable2.Rows[0]["UploadSecrecyApp"]);
					txt_allowSelectPhotoVisit.Checked = Function.ToString(dataTable2.Rows[0]["AllowSelectPhotoVisit"]) == "Y";
					txt_DashboardUrl.EditValue = Function.ToString(dataTable2.Rows[0]["DefaultAvatar"]);
					txt_LogoUrl.EditValue = Function.ToString(dataTable2.Rows[0]["Logo"]);
					txt_DashboardUrl.EditValue = Function.ToString(dataTable2.Rows[0]["DashboardUrl"]);
					txt_GoogleApiKey.EditValue = Function.ToString(dataTable2.Rows[0]["GoogleApiKey"]);
					btn_SeriesOutlet.EditValue = Function.ToString(dataTable2.Rows[0]["DefaultSeriesStore"]);
					txt_allowCheckInFarFromStore.Checked = Function.ToString(dataTable2.Rows[0]["AllowCheckInFarFromStore"]) == "Y";
					txt_allowUpdateStoreLocation.Checked = Function.ToString(dataTable2.Rows[0]["AllowUpdateStoreLocation"]) == "Y";
					txt_hideVanOrder.Checked = Function.ToString(dataTable2.Rows[0]["HideVanOrder"]) == "Y";
					txt_SaveDeliveryDraft.Checked = Function.ToString(dataTable2.Rows[0]["SaveDeliveryDraft"]) == "Y";
					txt_allowSkipLocationCheckFinish.Checked = Function.ToString(dataTable2.Rows[0]["AllowSkipLocationCheckFinish"]) == "Y";
					txt_distance.EditValue = Function.ParseDouble(dataTable2.Rows[0]["Distance"]);
					txt_appFirebaseName.EditValue = Function.ToString(dataTable2.Rows[0]["AppFirebaseName"]);
					txt_appFirebaseKey.EditValue = Function.ToString(dataTable2.Rows[0]["AppFirebaseKey"]);
					look_AuthorizationMode.EditValue = Function.ToString(dataTable2.Rows[0]["AuthorizationMode"]);
					look_warehouseInventoryType.EditValue = (string.IsNullOrEmpty(Function.ToString(dataTable2.Rows[0]["WarehouseInventoryType"])) ? "O" : Function.ToString(dataTable2.Rows[0]["WarehouseInventoryType"]));
					txt_allowUseGoogleApiPaid.Checked = Function.ToString(dataTable2.Rows[0]["AllowUseGoogleApiPaid"]) == "Y";
					txt_trackingEmployeeInterval.EditValue = Function.ParseDouble(dataTable2.Rows[0]["TrackingEmployeeInterval"]);
					txt_trackingRequestInterval.EditValue = Function.ParseDouble(dataTable2.Rows[0]["TrackingRequestInterval"]);
					txt_distanceSaveTracking.EditValue = Function.ParseDouble(dataTable2.Rows[0]["DistanceSaveTracking"]);
					txt_allowUseMultipleGoogleApiKey.Checked = Function.ToString(dataTable2.Rows[0]["AllowUseMultipleGoogleApiKey"]) == "Y";
					txt_GoogleApiKeyIos.EditValue = Function.ToString(dataTable2.Rows[0]["GoogleApiKeyIos"]);
					txt_GoogleApiKeyWeb.EditValue = Function.ToString(dataTable2.Rows[0]["GoogleApiKeyWeb"]);
					SetVisibleMultipleGoogleApi();
					txt_MarkerSize.EditValue = Function.ParseDouble(dataTable2.Rows[0]["MarkerSize"]);
					txt_CurrentMarkerSize.EditValue = Function.ParseDouble(dataTable2.Rows[0]["CurrentMarkerSize"]);
				}
			}
		}
		catch (Exception ex)
		{
			Logging.Write("ERROR", new StackTrace(new StackFrame(0)).ToString().Substring(5, new StackTrace(new StackFrame(0)).ToString().Length - 5), ex.Message);
			WinCommons.Error(Enums.MessageCode.ExceptionMessage, ex.Message);
		}
