	public void LoadApzObjectType()
	{
		List<string> list = (from ApzObjectTypes v in Enum.GetValues(typeof(ApzObjectTypes))
			select v.ToString().Replace("o", "")).ToList();
		DataTable dataTable = new DataTable
		{
			Columns = { 
			{
				"ObjType",
				typeof(string)
			} }
		};
		foreach (string item in list)
		{
			DataRow dataRow = dataTable.NewRow();
			dataRow["ObjType"] = item;
			dataTable.Rows.Add(dataRow);
		}
		col_ChooseObjType.DisplayMember = "ObjType";
		col_ChooseObjType.ValueMember = "ObjType";
		col_ChooseObjType.DataSource = dataTable;
	}

	public void CheckLocationSetting()
	{
		try
		{
			if (txt_allowCheckInFarFromStore.Checked)
			{
				txt_allowUpdateStoreLocation.Enabled = false;
				txt_distance.Enabled = false;
				txt_allowSkipLocationCheckFinish.Enabled = false;
				lbl_distance.Enabled = false;
				lbl_allowUpdateStoreLocation.Enabled = false;
				lbl_allowSkipLocationCheckFinish.Enabled = false;
			}
			else
			{
				txt_allowUpdateStoreLocation.Enabled = true;
				txt_distance.Enabled = true;
				txt_allowSkipLocationCheckFinish.Enabled = true;
				lbl_distance.Enabled = true;
				lbl_allowUpdateStoreLocation.Enabled = true;
				lbl_allowSkipLocationCheckFinish.Enabled = true;
			}
		}
		catch (Exception ex)
		{
			Logging.Write("ERROR", new StackTrace(new StackFrame(0)).ToString().Substring(5, new StackTrace(new StackFrame(0)).ToString().Length - 5), ex.Message);
			WinCommons.Error(Enums.MessageCode.ExceptionMessage, ex.Message);
		}
	}

	private async void btn_Functions_Click(object sender, EventArgs e)
	{
		btn_Functions.Enabled = false;
		try
		{
			if (FormMode == Enums.FormViewModeType.View)
			{
				Close();
				return;
			}
			DataTable tableStructure = WinFuntions.GetTableStructure("APZ_OADM");
			WinFuntions.GetTableStructure("APZ_ATC2");
			DataRow dataRow = tableStructure.NewRow();
			dataRow["DisableSplitFolder"] = chk_DisableSplitFolder.EditValue;
			dataRow["AutoSaveDraftApproval"] = chk_AutoGenerateDocument.EditValue;
			dataRow["CheckPromotion"] = chk_CheckPromotion.EditValue;
			dataRow["TaskAsgn"] = rd_ORM.EditValue;
			dataRow["DflLng"] = txtLanguage.EditValue;
			dataRow["SearchDate"] = calSearchRange.EditValue;
			dataRow["CheckOpenFormPR"] = chk_CheckOpenForm.EditValue;
			dataRow["IngoreActiveEmp"] = chk_IngoreActiveWhenSearch.EditValue;
			tableStructure.Rows.Add(dataRow);
			tableStructure.AcceptChanges();
			gc_Path.DataSourceTable.AcceptChanges();
			DataTable dataSourceTable = gc_Path.DataSourceTable;
			DataTable dataTable = _ds.Tables[2].Clone();
			DataRow dataRow2 = dataTable.NewRow();
			dataRow2["ID"] = 1;
			dataRow2["AppName"] = "i-DMS";
			dataRow2["UploadServer"] = Function.ToString(txt_UploadServer.EditValue);
			dataRow2["UploadSecrecyApp"] = Function.ToString(txt_uploadSecrecyApp.EditValue);
			dataRow2["DefaultAvatar"] = Function.ToString(txt_DashboardUrl.EditValue);
			dataRow2["Logo"] = Function.ToString(txt_LogoUrl.EditValue);
			dataRow2["DashboardUrl"] = Function.ToString(txt_DashboardUrl.EditValue);
			dataRow2["GoogleApiKey"] = Function.ToString(txt_GoogleApiKey.EditValue);
			dataRow2["DefaultSeriesStore"] = Function.ParseInt(btn_SeriesOutlet.EditValue);
			dataRow2["AllowSelectPhotoVisit"] = (txt_allowSelectPhotoVisit.Checked ? "Y" : "N");
			dataRow2["AllowCheckInFarFromStore"] = (txt_allowCheckInFarFromStore.Checked ? "Y" : "N");
			dataRow2["AllowUpdateStoreLocation"] = (txt_allowUpdateStoreLocation.Checked ? "Y" : "N");
			dataRow2["HideVanOrder"] = (txt_hideVanOrder.Checked ? "Y" : "N");
			dataRow2["SaveDeliveryDraft"] = (txt_SaveDeliveryDraft.Checked ? "Y" : "N");
			dataRow2["Distance"] = Function.ParseDouble(txt_distance.EditValue);
			dataRow2["AllowSkipLocationCheckFinish"] = (txt_allowSkipLocationCheckFinish.Checked ? "Y" : "N");
			dataRow2["AppFirebaseName"] = Function.ToString(txt_appFirebaseName.EditValue);
			dataRow2["AppFirebaseKey"] = Function.ToString(txt_appFirebaseKey.EditValue);
			dataRow2["AuthorizationMode"] = Function.ToString(look_AuthorizationMode.EditValue);
			dataRow2["WarehouseInventoryType"] = Function.ToString(look_warehouseInventoryType.EditValue);
			dataRow2["AllowUseGoogleApiPaid"] = (txt_allowUseGoogleApiPaid.Checked ? "Y" : "N");
			dataRow2["TrackingEmployeeInterval"] = Function.ParseDouble(txt_trackingEmployeeInterval.EditValue);
			dataRow2["TrackingRequestInterval"] = Function.ParseDouble(txt_trackingRequestInterval.EditValue);
			dataRow2["DistanceSaveTracking"] = Function.ParseDouble(txt_distanceSaveTracking.EditValue);
			dataRow2["AllowUseMultipleGoogleApiKey"] = (txt_allowUseMultipleGoogleApiKey.Checked ? "Y" : "N");
			dataRow2["GoogleApiKeyIos"] = Function.ToString(txt_GoogleApiKeyIos.EditValue);
			dataRow2["GoogleApiKeyWeb"] = Function.ToString(txt_GoogleApiKeyWeb.EditValue);
			dataRow2["MarkerSize"] = Function.ParseDouble(txt_MarkerSize.EditValue);
			dataRow2["CurrentMarkerSize"] = Function.ParseDouble(txt_CurrentMarkerSize.EditValue);
			dataTable.Rows.Add(dataRow2);
			dataTable.AcceptChanges();
			tableStructure.TableName = "APZ_OADM";
			dataSourceTable.TableName = "APZ_ATC2";
			dataTable.TableName = "APZ_D_OAPC";
			_ds.Tables.Clear();
			_ds.Tables.Add(tableStructure);
			_ds.Tables.Add(dataSourceTable);
			_ds.Tables.Add(dataTable.Copy());
			gc_Path.DataSource = dataSourceTable;
			WinCommons._OpenProcessing();
			HttpResult httpResult = await _httpClient.AdditionalGeneralSettingsClient.Save(_ds);
			if (!string.IsNullOrEmpty(httpResult.Message))
			{
				WinCommons.Error(Enums.MessageCode.None, httpResult.Message);
				return;
			}
			WinCommons.Success(Enums.MessageCode.SaveSuccess, "");
			FormMode = Enums.FormViewModeType.View;
			GlobalData.AdditionalGeneralSettings = await _httpClient.AdditionalGeneralSettingsClient.GetData();
		}
		catch (Exception ex)
		{
			Logging.Write("ERROR", new StackTrace(new StackFrame(0)).ToString().Substring(5, new StackTrace(new StackFrame(0)).ToString().Length - 5), ex.Message);
			WinCommons.Error(Enums.MessageCode.ExceptionMessage, ex.Message);
		}
		finally
		{
			WinCommons._CloseProcessing();
			btn_Functions.Enabled = true;
		}
	}

