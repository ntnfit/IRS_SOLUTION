CREATE procedure ILD_F_SoSanhBaoGia (
	in PRNo	table(Code int),
	---in PRNo	int,
	 --in DocID	int,
	in Vendor	table(Code nvarchar(50)),

	out tab_result	table( 
	
	    PRNo nvarchar(50),
	    Department nvarchar(70),
	    RequiredDate date,
	   	--
		CardCode nvarchar(50),
		CardName nvarchar(100),
		--
		STTVendor int,
		ItemCode nvarchar(50),
		Dscription	nvarchar(150),
		Required_Qty	decimal(21,6),
		-- Bao gia
		DocEntryPQ int,
		-- 1
		DeliveryDate1 date,
		PaymentTerm1 nvarchar(100),
		DeliveryTerm1 nvarchar(100),
		Others1 nvarchar(100),
		CardCode1 nvarchar(50),
		CardName1 nvarchar(150),
		Quoted_Qty1	decimal(21,6),
		UnitPrice1 decimal(21,6),
		Amount1 decimal(21,6),
		-- 2
		DeliveryDate2 date,
		PaymentTerm2 nvarchar(100),
		DeliveryTerm2 nvarchar(100),
		Others2 nvarchar(100),
		CardCode2 nvarchar(50),
		CardName2 nvarchar(150),
		Quoted_Qty2	decimal(21,6),
		UnitPrice2 decimal(21,6),
		Amount2 decimal(21,6),
		--3
		DeliveryDate3 date,
		PaymentTerm3 nvarchar(100),
		DeliveryTerm3 nvarchar(100),
		Others3 nvarchar(100),
		CardCode3 nvarchar(50),
		CardName3 nvarchar(150),
		Quoted_Qty3	decimal(21,6),
		UnitPrice3 decimal(21,6),
		Amount3 decimal(21,6),
			
		
		RptNameVN 		nvarchar(300), 
		
		--
		
		CompName 		nvarchar(300), 
		CompAddr 		nvarchar(300),
		CompTel 		nvarchar(30), 
		CompFax 		nvarchar(30), 
		CompTaxNum		nvarchar(30),
		
		--format number
		AmountDec		smallint,
		QtyDec			smallint,
		PriceDec		smallint,
		RateDec			smallint,
		PercentDec		smallint,
		DecSep			nvarchar(1),
		ThousSep		nvarchar(1)
	)
)
as
begin
--declare DocEntry int;
-- select  3 into DocEntry from dummy;
	----------------------------------------------------------------------------------------------------------------------------
	 create local temporary table #tbl as (select * from :tab_result);
	-- REPORT ----------------------------------------------------------------------------------------------------------------
---Table Item từ table Purchase Request

create local temporary table #PR
(
	ItemCode nvarchar(50),
	Dscription	nvarchar(100),
	Required_Qty	decimal(21,6)
);
insert into #PR (ItemCode,Dscription,Required_Qty)
select "ItemCode","Dscription","Quantity" as "Required_Qty"  
from PRQ1 a
where 
--a."DocEntry"  =  :PRNo;
(ifnull((select STRING_AGG(cast(Code as smallint)) from :PRNo), '') = '' 
			  	or a."DocEntry" in (select Code from :PRNo));


---- 

create local temporary table #VenDor
(
	 STT int not null primary key generated by default as IDENTITY,
	 CardCode nvarchar(50)
);

insert into  #VenDor (CardCode)
select top 3 distinct b."CardCode"
from PQT1 a
inner join  OPQT b on  a."DocEntry"  = b."DocEntry"

where   a."BaseType" = '1470000113' 
and 
(ifnull((select STRING_AGG(Code) from :VenDor), '') = '' 
			  	or b."CardCode" in (select Code from :VenDor))
			  	
and
--a."BaseEntry"  =  :PRNo;
(ifnull((select STRING_AGG(cast(Code as smallint)) from :PRNo), '') = '' 
			  	or a."BaseEntry" in (select Code from :PRNo));


--- Purchase Quotation

create local temporary table #PQ_PR -- Bao gia tu nha cung cap
(
	STTVendor int,
	DocEntryPQ int,
	CardCode nvarchar(50),
	CardName nvarchar(150),
	ItemCode nvarchar(50),
	Dscription nvarchar(150),
	
	Required_Qty decimal(21,6),
	
	Quoted_Qty	decimal(21,6),
	UnitPrice decimal(21,6),
	Amount decimal(21,6),
	
	DeliveryDate date,
	PaymentTerm nvarchar(100),
	DeliveryTerm nvarchar(100),
	Others nvarchar(100)
	
);

Insert into #PQ_PR (STTVendor,DocEntryPQ,CardCode,CardName,ItemCode,Dscription,Required_Qty,Quoted_Qty,UnitPrice, Amount, 
					DeliveryDate,PaymentTerm)
select  
		MAX(d.STT),
		Max(a."DocEntry") as "DocEntry",
		b."CardCode",
		b."CardName",
		a."ItemCode",
		c.Dscription,
		max(c.Required_Qty) as "Required_Qty" ,
		Max(a."Quantity") as "Quantity",
		case when Max("Currency") = 'VND' then (Max(a."Price") / Max(a."Rate")) 
		else   Max(a."Price") * Max(a."Rate") end as "Price",
		
		Max(a."LineTotal") as  "LineTotal",
		a."ShipDate" as "DeliveryDate",
		e."PymntGroup"
		
from PQT1 a
inner join  OPQT b on  a."DocEntry"  = b."DocEntry"
left join #Vendor d on b."CardCode" = d.CardCode
inner join  #PR c on c.ItemCode = a."ItemCode"

left join  OCTG e  on b."GroupNum"  = e."GroupNum"  -- Paymenterm

where   a."BaseType" = '1470000113' 

and 
--a."BaseEntry"  = :PRNo
(ifnull((select STRING_AGG(cast(Code as smallint)) from :PRNo), '') = '' 
			  	or a."BaseEntry" in (select Code from :PRNo))
 

group by b."CardCode",
		 b."CardName",
		 a."ItemCode",
		 c.Dscription,
		 a."ShipDate",
		 e."PymntGroup"
order by b."CardCode";

--
 
-----
JE = select  a.ItemCode,a.Dscription,a.Required_Qty,
		
		Vendor1.DeliveryDate as "DeliveryDate1",
		Vendor1.PaymentTerm as  "PaymentTerm1",
		'' as "DeliveryTerm1",
		'' as "Others1",
	    
	   Vendor1.CardCode as "CardCode1",
	   Vendor1.CardName as  "CardName1",
	   Vendor1.Quoted_Qty as  "Quoted_Qty1",
	   Vendor1.UnitPrice as  "UnitPrice1",
	   Vendor1.Amount as  "Amount1",
	   
	   
	   -- Vendor 2

		Vendor2.DeliveryDate as "DeliveryDate2",
		Vendor2.PaymentTerm as  "PaymentTerm2",
		'' as "DeliveryTerm2",
		'' as "Others2",	   
	   Vendor2.CardCode as "CardCode2",
	   Vendor2.CardName as  "CardName2",
	   Vendor2.Quoted_Qty as  "Quoted_Qty2",
	   Vendor2.UnitPrice as  "UnitPrice2",
	   Vendor2.Amount as  "Amount2",
	   
	   -- Vendor 3
	   	Vendor3.DeliveryDate as "DeliveryDate3",
		Vendor3.PaymentTerm as  "PaymentTerm3",
		'' as "DeliveryTerm3",
		'' as "Others3",
	   Vendor3.CardCode as "CardCode3",
	   Vendor3.CardName as  "CardName3",
	   Vendor3.Quoted_Qty as  "Quoted_Qty3",
	   Vendor3.UnitPrice as  "UnitPrice3",
	   Vendor3.Amount as  "Amount3"
	   
from #PR a

left outer join  
(  
	select *  from #PQ_PR 
	where  STTVENDOR  = 1 ) as Vendor1 on a.ItemCode = Vendor1.ItemCode

left outer join  
(  
	select *  from #PQ_PR 
	where  STTVENDOR  = 2 ) as Vendor2 on a.ItemCode = Vendor2.ItemCode
	
left outer join  
(  
	select *  from #PQ_PR 
	where  STTVENDOR  = 3 ) as Vendor3 on a.ItemCode = Vendor3.ItemCode	;

---------------------

--- insert #tbl 

	insert into  #tbl  (ItemCode,Dscription,Required_Qty,
						DeliveryDate1,PaymentTerm1,DeliveryTerm1,Others1,CardCode1,CardName1,Quoted_Qty1,UnitPrice1,Amount1,
						DeliveryDate2,PaymentTerm2,DeliveryTerm2,Others2,CardCode2,CardName2,Quoted_Qty2,UnitPrice2,Amount2,
						DeliveryDate3,PaymentTerm3,DeliveryTerm3,Others3,CardCode3,CardName3,Quoted_Qty3,UnitPrice3,Amount3)
						
	select   
			ItemCode,
			Dscription,
			Required_Qty,
			
			"DeliveryDate1",
			"PaymentTerm1",
			"DeliveryTerm1",
			"Others1",
 
			"CardCode1",
			"CardName1",
			"Quoted_Qty1",
			"UnitPrice1",
			"Amount1",
			-- 2
			"DeliveryDate2",
			"PaymentTerm2",
			"DeliveryTerm2",
			"Others2",
			
			"CardCode2",
			"CardName2",
			"Quoted_Qty2",
			"UnitPrice2",
			"Amount2",
			-- 3
			"DeliveryDate3",
			"PaymentTerm3",
			"DeliveryTerm3",
			"Others3",
			
			"CardCode3",
			"CardName3",
			"Quoted_Qty3",
			"UnitPrice3",
			"Amount3"
	from :JE a  
	
	order by a.ItemCode; 

--------

update #tbl
set PRNo   = (select STRING_AGG("U_JVNumber",', ')
				from  OPRQ a
				--where "DocEntry"  = :PRNo),
				 where "DocEntry"   in (select Code from :PRNo)),
				
	Department   = (select max(b."Name")
				from  OPRQ a
				left join OUDP b on a."Department"  = b."Code" 
				--where "DocEntry"  = :PRNo),
				where "DocEntry"   in (select Code from :PRNo)),	
						
	RequiredDate   = (select  Max("ReqDate")
				from  OPRQ a
				--where "DocEntry"  = :PRNo);
				 where "DocEntry"   in (select Code from :PRNo));				
	    

---- 
 
	
	 
	
	update x set 
			AmountDec	= y."SumDec",
			QtyDec		= y."QtyDec",
			PriceDec	= y."PriceDec",
			RateDec		= y."RateDec",
			PercentDec	= y."PercentDec",
			DecSep		= y."DecSep",
			ThousSep	= y."ThousSep",
			RptNameVN = N'QUOTATION COMPARISON'
	from #tbl x inner join OADM y on 1=1;
	-----	
tab_result =	select * from #tbl;
	----

drop table #PR;
drop table #PQ_PR;
drop table #VenDor;
drop table #tbl;



end;


