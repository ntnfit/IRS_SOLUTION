CREATE PROCEDURE VAS_CN02_DN (
	in username			nvarchar(100),
	in branch			int,
	in bp				table(Code nvarchar(50)),
	in acct				table(Code nvarchar(50)),
	in fdate			timestamp,
	in tdate			timestamp,
	in curr				nvarchar(10),
	in remarks			varchar(1),
	in typ				varchar(1),
	out out_Tb			table(
		Period		tinyint,
		ID			int,
		BefJEId		int,
		BefJELine	int,
		BefType		int,
		BefEntry	int,
		BefDDate	timestamp,
		BefMemo		nvarchar(600),
		BefJEMemo	nvarchar(300),
		BefDocMemo	nvarchar(300),
		BefNo		nvarchar(100),
		BefBalFC	numeric(21,6),
		BefBalLC	numeric(21,6),
		CurIRId		int,
		CurIRLine	int,
		CurIRType	int,
		CurJEId		int,
		CurJELine	int,
		CurType		int,
		CurEntry	int,
		CurDDate	timestamp,
		CurMemo		nvarchar(600),
		CurJEMemo	nvarchar(300),
		CurDocMemo	nvarchar(300),
		CurNo		nvarchar(100),
		CurDebFC	numeric(21,6),
		CurDebLC	numeric(21,6),
		CurCredFC	numeric(21,6),
		CurCredLC	numeric(21,6),
		AftJEId		int,
		AftJELine	int,
		AftDDate	timestamp,
		AftMemo		nvarchar(600),
		AftNo		nvarchar(100),
		AftBalFC	numeric(21,6),
		AftBalLC	numeric(21,6),
		
		Accounts	nvarchar(2000),
		Currency	nvarchar(30),
		CurrSym		nvarchar(10),
		CardCode	nvarchar(30),
		CardName	nvarchar(100),

		RN			int,
		Curr		nvarchar(30),
		QtyDec		int,
		PriceDec	int,
		SumDecLC	int,
		SumDecFC	int,
		DecSep		nvarchar(1),
		ThousSep	nvarchar(1),
		Logo		nvarchar(100),
		DateTitle	nvarchar(200),
		CompName	nvarchar(300),
		CompAdd		nvarchar(500)
	)
)
AS
BEGIN
--	declare usercode nvarchar(20) ;
--	select x."USER_CODE" into usercode from OADM x0 left join OUSR x on x."U_NAME" = :username;
	
	list_branch = 
			select IFNULL(a."BPLId",0) BPLId
			from 
				OADM a0
				left join OBPL a on 1=1
--				left join USR6 b on b."UserCode" = :usercode and a."BPLId" = b."BPLId"
			where
				:branch in (0,a."BPLId");
	
	create local temporary table #list_JE (
		 FCCurrency				nvarchar(10),
		 Account				nvarchar(50),
		 ShortName				nvarchar(50),
		 TransId				int,
		 Line_ID				int,
		 TransType				int,
		 CreatedBy				int,
		 RefDate				timestamp,
		 LineMemo				nvarchar(254),
		 FCDebit				numeric(21,6),
		 FCCredit				numeric(21,6),
		 Debit					numeric(21,6),
		 Credit					numeric(21,6),
		 DebCred				varchar(1),
		 ContraAct				nvarchar(50)
	); 
	insert into #list_JE (FCCurrency,Account,ShortName,TransId,Line_ID,TransType,CreatedBy,RefDate,LineMemo,FCDebit,FCCredit,Debit,Credit,DebCred,ContraAct)
	select
			case LTRIM(IFNULL(a."FCCurrency",'')) when '' then d."MainCurncy" else a."FCCurrency" end as FCCurrency
			,a."Account",a."ShortName",a."TransId",a."Line_ID",a."TransType",a."CreatedBy",a."RefDate",a."LineMemo"
			,a."FCDebit",a."FCCredit"
			,case when :typ = 'L' then a."Debit" else a."SYSDeb" end Debit
			,case when :typ = 'L' then a."Credit" else a."SYSCred" end Credit
			,a."DebCred",a."ContraAct"
		from 
			JDT1 a
			inner join :bp b on a."ShortName" = b.Code
			inner join :acct c on a."Account" = c.Code
			inner join OADM d on 1=1
		where
			a."RefDate" <= :tdate
			and (a."BPLId"=branch or branch=0)
			and (:curr is null or (case LTRIM(IFNULL(a."FCCurrency",'')) when '' then d."MainCurncy" else a."FCCurrency" end) = :curr);
	
	create local temporary table #tbl (
		Period		tinyint,
		ID			int not null primary key generated by default as IDENTITY,
		BefJEId		int,
		BefJELine	int,
		BefType		int,
		BefEntry	int,
		BefDDate	timestamp,
		BefMemo		nvarchar(600),
		BefJEMemo	nvarchar(300),
		BefDocMemo	nvarchar(300),
		BefNo		nvarchar(100),
		BefBalFC	numeric(21,6),
		BefBalLC	numeric(21,6),
		CurIRId		int,
		CurIRLine	int,
		CurIRType	int,
		CurJEId		int,
		CurJELine	int,
		CurType		int,
		CurEntry	int,
		CurDDate	timestamp,
		CurMemo		nvarchar(600),
		CurJEMemo	nvarchar(300),
		CurDocMemo	nvarchar(300),
		CurNo		nvarchar(100),
		CurDebFC	numeric(21,6),
		CurDebLC	numeric(21,6),
		CurCredFC	numeric(21,6),
		CurCredLC	numeric(21,6),
		AftJEId		int,
		AftJELine	int,
		AftDDate	timestamp,
		AftMemo		nvarchar(600),
		AftNo		nvarchar(100),
		AftBalFC	numeric(21,6),
		AftBalLC	numeric(21,6),
		
		Accounts	nvarchar(2000),
		Currency	nvarchar(30),
		CurrSym		nvarchar(10),
		CardCode	nvarchar(30),
		CardName	nvarchar(100),

		RN			int,
		Curr		nvarchar(30),
		QtyDec		int,
		PriceDec	int,
		SumDecLC	int,
		SumDecFC	int,
		DecSep		nvarchar(1),
		ThousSep	nvarchar(1),
		Logo		nvarchar(100),
		DateTitle	nvarchar(200),
		CompName	nvarchar(300),
		CompAdd		nvarchar(500)
	);
			
	insert into #tbl (Period,Currency,CardCode,BefJEId,BefJELine,BefType,BefEntry,BefDDate,BefJEMemo,BefBalFC,BefBalLC,CurIRId,CurIRLine,CurIRType,CurDDate,CurDebFC,CurDebLC,CurCredFC,CurCredLC)
	select
		0
		,a1.FCCurrency
		,a1.ShortName
		,a1.TransId
		,a1.Line_ID
		,a1.TransType
		,a1.CreatedBy
		,a1.RefDate
		,a1.LineMemo
		,a1.BalFC
		,a1.BalLC
		,b1."ReconNum"
		,b1."LineSeq"
		,c1."ReconType"
		,c1."ReconDate"
		,CASE b1."IsCredit" when 'C' then b1."ReconSumFC" else 0 end
		,case when :typ = 'L' then (CASE b1."IsCredit" when 'C' then b1."ReconSum" else 0 end) else (CASE b1."IsCredit" when 'C' then b1."ReconSumSC" else 0 end) end
		,CASE b1."IsCredit" when 'D' then b1."ReconSumFC" else 0 end
		,case when :typ = 'L' then (CASE b1."IsCredit" when 'D' then b1."ReconSum" else 0 end) else (case b1."IsCredit" when 'D' then b1."ReconSumSC" else 0 end) end
	from
		(select
			a.FCCurrency
			,a.ShortName
			,a.TransId
			,a.Line_ID
			,a.TransType
			,a.CreatedBy
			,a.RefDate
			,a.LineMemo
			,(a.FCDebit-a.FCCredit)-IFNULL(SUM(case b."IsCredit" when 'D' then b."ReconSumFC" else -b."ReconSumFC" end),0) as BalFC
			,(a.Debit-a.Credit)-IFNULL(SUM(case when :typ = 'L' then case b."IsCredit" when 'D' then b."ReconSum" else -b."ReconSum" end else case b."IsCredit" when 'D' then b."ReconSumSC" else -b."ReconSumSC" end end),0) as BalLC
		from
			:bp a0
			left join #list_JE a on a.ShortName=a0.Code
			left join ITR1 b on a.TransId = b."TransId" and a.Line_ID = b."TransRowId"
								and exists(select 1 from OITR where "ReconNum" = b."ReconNum" and "ReconDate" < :fdate)
		where
			a.RefDate < :fdate
			and not exists
				(select 1
				from
					OJDT x
					inner join OJDT y on x."StornoToTr" = y."TransId"
				where
					(x."RefDate" between :fdate and :tdate and y."RefDate" between :fdate and :tdate)
					and (x."TransId" = a.TransId or y."TransId" = a.TransId))
		group by
			a.FCCurrency
			,a.ShortName
			,a.TransId
			,a.Line_ID
			,a.TransType
			,a.CreatedBy
			,a.RefDate
			,a.LineMemo
			,(a.Debit-a.Credit)
			,(a.FCDebit-a.FCCredit)
		having
			(a.Debit-a.Credit)<>IFNULL(SUM(case when :typ = 'L' then case b."IsCredit" when 'D' then b."ReconSum" else -b."ReconSum" end else case b."IsCredit" when 'D' then b."ReconSumSC" else -b."ReconSumSC" end end),0)) a1
		left join ITR1 b1 on a1.TransId = b1."TransId" and a1.Line_ID = b1."TransRowId" and exists(select 1 from OITR t where t."ReconNum" = b1."ReconNum" and t."ReconDate" between :fdate and :tdate and not (t."ReconType" in (3,7) and exists(select 1 from ITR1 t1, ORCT t2 where t1."SrcObjTyp" = t2."ObjType" and t1."SrcObjAbs" = t2."DocEntry" and t1."ReconNum" = t."ReconNum" and t2."Canceled" <> 'N')))
		left join OITR c1 on b1."ReconNum" = c1."ReconNum";
	
	update b set CurJEId = a."TransId", CurJELine = a."TransRowId", CurType = a."SrcObjTyp", CurEntry = a."SrcObjAbs" from ITR1 a,#tbl b where a."ReconNum" = b.CurIRId and a."SrcObjTyp" in (24,46,321) and b.CurIRType in (3,0);
	update b set CurJEMemo = a."LineMemo" from JDT1 a,#tbl b where a."TransId" = b.CurJEId and a."Line_ID" = b.CurJELine;
	update #tbl set AftBalFC = (select MAX(BefBalFC)-SUM(-a.CurDebFC+a.CurCredFC) from #tbl a where a.BefJEId = #tbl.BefJEId and a.BefJELine = #tbl.BefJELine);
	update #tbl set AftBalLC = (select MAX(BefBalLC)-SUM(-a.CurDebLC+a.CurCredLC) from #tbl a where a.BefJEId = #tbl.BefJEId and a.BefJELine = #tbl.BefJELine);
	
	insert into #tbl (Period,Currency,CardCode,CurJEId,CurJELine,CurType,CurEntry,CurDDate,CurJEMemo,CurDebFC,CurDebLC,CurCredFC,CurCredLC)
	select
		1
		,a.FCCurrency
		,a.ShortName
		,a.TransId
		,a.Line_ID
		,a.TransType
		,a.CreatedBy
		,a.RefDate
		,a.LineMemo
		,a.FCDebit
		,a.Debit+IFNULL((select SUM(Debit-Credit) from #list_JE where a.TransType = '24' and a.DebCred = 'D' and TransId = a.TransId and ContraAct in ('515200','635300')),0)
		,a.FCCredit
		,a.Credit+IFNULL((select SUM(-Debit+Credit) from #list_JE where a.TransType = '24' and a.DebCred = 'C' and TransId = a.TransId and ContraAct in ('515200','635300')),0)
	from
		:bp a0
		left join #list_JE a on a0.Code = a.ShortName
	where
		a.RefDate between :fdate and :tdate
		and not exists(select 1 from #tbl tmp where tmp.CurJEId = a.TransId and tmp.CurJELine = a.Line_ID having SUM(tmp.CurDebLC-tmp.CurCredLC) = a.Debit-a.Credit)
		and not (a.TransType = '24' and a.ContraAct in ('515200','635300'))
		and not exists(select 1 from OINV where "ObjType" = a.TransType and "DocEntry" = a.CreatedBy and "CANCELED" <> 'N')
		and not exists(select 1 from ORCT where "ObjType" = a.TransType and "DocEntry" = a.CreatedBy and "Canceled" <> 'N')
		and not exists
			(select 1
			from
				OJDT x
				inner join OJDT y on x."StornoToTr" = y."TransId"
			where
				(x."RefDate" between :fdate and :tdate and y."RefDate" between :fdate and :tdate)
				and (x."TransId" = a.TransId or y."TransId" = a.TransId));
	
	update #tbl set CurCredFC = #tbl.CurCredFC-IFNULL((select SUM(a.CurCredFC) from #tbl a where a.Period = 0 and a.CurJEId = #tbl.CurJEId and a.CurJELine = #tbl.CurJELine),0) where #tbl.Period = 1 and #tbl.CurType = 24;
	update #tbl set CurCredLC = #tbl.CurCredLC-IFNULL((select SUM(a.CurCredLC) from #tbl a where a.Period = 0 and a.CurJEId = #tbl.CurJEId and a.CurJELine = #tbl.CurJELine),0) where #tbl.Period = 1 and #tbl.CurType = 24;

	delete from #tbl where Period = 1 and IFNULL(CurDebFC,0)=0 and IFNULL(CurDebLC,0)=0 and IFNULL(CurCredFC,0)=0 and IFNULL(CurCredLC,0)=0;
	
	update b set AftBalFC = tmp.BalFC, AftBalLC = tmp.BalLC
				from
					(select
						a.TransId
						,a.Line_ID
						,(a.FCDebit-a.FCCredit)-IFNULL(SUM(case b."IsCredit" when 'D' then b."ReconSumFC" else -b."ReconSumFC" end),0) as BalFC
						,(a.Debit-a.Credit)-IFNULL(SUM(case when :typ = 'L' then (case b."IsCredit" when 'D' then b."ReconSum" else -b."ReconSum" end) else (case b."IsCredit" when 'D' then b."ReconSumSC" else -b."ReconSumSC" end) end),0) as BalLC
					from
						:bp a0
						left join #list_JE a on a0.Code = a.ShortName
						left join ITR1 b on a.TransId = b."TransId" and a.Line_ID = b."TransRowId"
											and exists(select 1 from OITR where "ReconNum" = b."ReconNum" and "ReconDate" <= :tdate)
					where
						a.RefDate between :fdate and :tdate
					group by
						a.TransId
						,a.Line_ID
						,(a.Debit-a.Credit)
						,(a.FCDebit-a.FCCredit)
					having
						(a.Debit-a.Credit)<>IFNULL(SUM(case when :typ = 'L' then (case b."IsCredit" when 'D' then b."ReconSum" else -b."ReconSum" end) else (case b."IsCredit" when 'D' then b."ReconSumSC" else -b."ReconSumSC" end) end),0)) tmp,#tbl b
				where b.Period = 1 and b.CurJEId = tmp.TransId and b.CurJELine = tmp.Line_ID;
	
	update a set BefNo =	IFNULL(CASE BefType
								when 30 then (select "U_JVNumber" from OJDT where "TransId" = a.BefJEId)
								when 13 then (select "U_JVNumber" from OINV where "DocEntry" = a.BefEntry)
								when 14 then (select "U_JVNumber" from ORIN where "DocEntry" = a.BefEntry)
								when 203 then (select "U_JVNumber" from ODPI where "DocEntry" = a.BefEntry)
								when 24 then (select "U_JVNumber" from ORCT where "DocEntry" = a.BefEntry)
							END,cast(a.BefJEId as nvarchar)) from #tbl a;

	update a set CurNo =	IFNULL(CASE CurType
								when '30' then (select "U_JVNumber" from OJDT where "TransId" = a.CurJEId)
								when '13' then (select "U_JVNumber" from OINV where "DocEntry" = a.CurEntry)
								when '14' then (select "U_JVNumber" from ORIN where "DocEntry" = a.CurEntry)
								when '203' then (select "U_JVNumber" from ODPI where "DocEntry" = a.CurEntry)
								when '24' then (select "U_JVNumber" from ORCT where "DocEntry" = a.CurEntry)
							END,cast(a.CurJEId as nvarchar)) from #tbl a;

	update a set BefDocMemo =
						CASE BefType
							when '30' then (select "Memo" from OJDT where "TransId" = a.BefJEId)
							when '13' then (select "Comments" from OINV where "DocEntry" = a.BefEntry)
							when '14' then (select "Comments" from ORIN where "DocEntry" = a.BefEntry)
							when '203' then (select "Comments" from ODPI where "DocEntry" = a.BefEntry)
							when '24' then (select "Comments" from ORCT where "DocEntry" = a.BefEntry)
						END from #tbl a;

	update a set CurDocMemo =
						CASE CurType
							when '30' then (select "Memo" from OJDT where "TransId" = a.CurJEId)
							when '13' then (select "Comments" from OINV where "DocEntry" = a.CurEntry)
							when '14' then (select "Comments" from ORIN where "DocEntry" = a.CurEntry)
							when '203' then (select "Comments" from ODPI where "DocEntry" = a.CurEntry)
							when '24' then (select "Comments" from ORCT where "DocEntry" = a.CurEntry)
						END from #tbl a;
	
	update a set BefMemo =
		CASE :remarks
			when 'J' then BefJEMemo
			when 'D' then BefDocMemo
			when 'B' then IFNULL(BefJEMemo || '\ ','') || IFNULL(BefDocMemo,'')
		END from #tbl a;

	update a set CurMemo =
		CASE :remarks
			when 'J' then CurJEMemo
			when 'D' then CurDocMemo
			when 'B' then IFNULL(CurJEMemo || '\ ','') || IFNULL(CurDocMemo,'')
		END from #tbl a;

	update a set AftJEId = BefJEId, AftJELine = BefJELine, AftDDate = BefDDate, AftMemo = BefMemo from #tbl a where IFNULL(AftBalLC,0) <> 0 and Period = 0;
	update a set AftJEId = CurJEId, AftJELine = CurJELine, AftDDate = CurDDate, AftMemo = CurMemo from #tbl a where IFNULL(AftBalLC,0) <> 0 and Period = 1;
	
	update #tbl set Accounts = (select string_agg(x.Code,',') from :acct x);
	update b set CardName = a."CardName" from OCRD a,#tbl b where b.CardCode = a."CardCode";

	update a set CurrSym = case Currency when 'VND' then '' when 'USD' then '$' when 'JPY' then '�' end from #tbl a;

	update #tbl set RN = (select a.RN from (select ROW_NUMBER() OVER (PARTITION BY BefJEId,BefJELine ORDER BY CurIRId,CurIRLine) as RN, ID from #tbl) a where #tbl.ID = a.ID);

	update a set BefJEId=NULL,BefJELine=NULL,BefType=NULL,BefEntry=NULL,BefDDate=NULL,BefMemo=NULL,BefNo=NULL,BefBalFC=NULL,BefBalLC=NULL,AftJEId=NULL,AftJELine=NULL,AftDDate=NULL,AftMemo=NULL,AftNo=NULL,AftBalFC=NULL,AftBalLC=NULL from #tbl a where Period = 0 and RN <> 1;
	
	update c set CompName = a."PrintHeadr", CompAdd = b."Street" from OADM a,ADM1 b,#tbl c where :branch in ('-1','0');
	update b set CompName = a."BPLName", CompAdd = a."Street" from OBPL a,#tbl b where a."BPLId" = :branch;
	
	update b set Curr = case :typ when 'L' then a."MainCurncy" else a."SysCurrncy" end, SumDecLC = a."SumDec", SumDecFC = a."SumDec", DecSep = a."DecSep", ThousSep = a."ThousSep", DateTitle = N'Ng�y........th�ng........n?m........ ' || char(13) || char(10) || N'Prepared on the date................' from OADM a,#tbl b;
	update b set Logo = a."BitmapPath" || IFNULL(a."LogoFile",'') from OADP a,#tbl b;
	
	update b set SumDecLC = case when a."Decimals"=-1 then b.SumDecLC else a."Decimals" end from OCRN a,#tbl b where a."CurrCode" = b.Curr;
	update b set SumDecFC = case when a."Decimals"=-1 then b.SumDecFC else a."Decimals" end from OCRN a,#tbl b where a."CurrCode" = b.Currency;
	
	out_Tb = select * from #tbl;
	--select * from #tbl;
	drop table #list_JE;
	drop table #tbl;
	
END

