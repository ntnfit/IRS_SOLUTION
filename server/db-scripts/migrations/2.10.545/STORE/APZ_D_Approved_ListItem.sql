CREATE PROCEDURE APZ_D_Approved_ListItem (IN objType nvarchar(20),
in userCode nvarchar(50) default '',
in fromDate nvarchar(100) default null,
in toDate nvarchar(100) default null,
in pageIndex int default 1,
in typeFilter nvarchar(10) default 'A', -- A: all, Y: đã duyệt, N: chưa duyệt, C: không duyệt
in searchText nvarchar(100) default '',
in wddCode int default -1)
AS
BEGIN

declare tblStatus table("Status" nvarchar(10),"Name" nvarchar(500));
declare lowLimit int;
declare upLimit int;
declare userId int;
create local temporary table #tmpApproval (
"WddCode" int,
"WtmCode" int,
"WtmName" nvarchar(100),
"CardCode" nvarchar(15),
"CardName" nvarchar(100),
"OwnerId" int,
"DocNo" nvarchar(50),
"ObjType" int,
"DocType" nvarchar(100),
"DocDate" datetime,
"DocDueDate" datetime,
"DocTotal" decimal(19,6),
"DocCur" varchar(10),
"IsDraft" char(1),
"UserId" int,
"UserCode" varchar(10),
"UserName" nvarchar(50),
"UpdateDate" datetime,
"UpdateTime" int,
"Status" char(1),
"Remarks" nclob,
"RequestType" char(1),--dùng để phân biệt my request và approval request
"ItemCheck" varchar(5),
"ProcesStat" varchar(5));


insert into :tblStatus
select '-',N'Without' from DUMMY
UNION ALL
select 'W',N'Pending' from DUMMY
UNION ALL
select 'Y',N'Approved' from DUMMY
UNION ALL
select 'N',N'Rejected' from DUMMY
UNION ALL
select 'P',N'Generated' from DUMMY
UNION ALL
select 'A',N'Generated by Authorizer' from DUMMY
UNION ALL
select 'C',N'Canceled' FROM DUMMY;



lowLimit = 20 * :pageIndex - 20;
upLimit = :pageIndex * 20;
select ifnull((select top 1 "USERID" from OUSR where "USER_CODE" = :userCode), -1) into userId from DUMMY;

call APZ_Function_GetApprovalTemplateData(:userId, 'All', 'P', result);

INSERT INTO #tmpApproval ("WddCode","WtmCode", "WtmName", "CardCode", "CardName", "OwnerId", "DocNo", "ObjType", "DocType", "DocDate", "DocDueDate", "DocTotal", "DocCur", "IsDraft", "UserId", "UserCode", "UserName", "UpdateDate", "UpdateTime", "Status", "Remarks", "RequestType", "ItemCheck","ProcesStat")
select * from :result;

create local temporary table #tempApproval(
"WddCode" int,
"WtmCode" int,
"WtmName" nvarchar(100),
"CardCode" nvarchar(15),
"CardName" nvarchar(100),
"OwnerId" int,
"DocNo" nvarchar(50),
"ObjType" int,
"DocType" nvarchar(100),
"DocDate" datetime,
"DocDueDate" datetime,
"DocTotal" decimal(19,6),
"DocCur" varchar(10),
"IsDraft" char(1),
"UserId" int,
"UserCode" varchar(10),
"UserName" nvarchar(50),
"UpdateDate" datetime,
"UpdateTime" int,
"Status" char(1),
"Remarks" nclob,
"RequestType" char(1),--dùng để phân biệt my request và approval request
"ItemCheck" varchar(5),
"ProcesStat" varchar(5),
"StatusName" nvarchar(100),
"ProcessUserId" int,
"ProcessUserName" nvarchar(100),
"OwnerUserName" nvarchar(100),
"UserStatus" nvarchar(5),
"CurrentStepRemarks" nvarchar(100),
"CurrentStep" int,
"StepStatus" nvarchar(10)
);

create local temporary table #tempFilterApproval(
"WddCode" int,
"WtmCode" int,
"WtmName" nvarchar(100),
"CardCode" nvarchar(15),
"CardName" nvarchar(100),
"OwnerId" int,
"DocNo" nvarchar(50),
"ObjType" int,
"DocType" nvarchar(100),
"DocDate" datetime,
"DocDueDate" datetime,
"DocTotal" decimal(19,6),
"DocCur" varchar(10),
"IsDraft" char(1),
"UserId" int,
"UserCode" varchar(10),
"UserName" nvarchar(50),
"UpdateDate" datetime,
"UpdateTime" int,
"Status" char(1),
"Remarks" nclob,
"RequestType" char(1),--dùng để phân biệt my request và approval request
"ItemCheck" varchar(5),
"ProcesStat" varchar(5),
"StatusName" nvarchar(100),
"ProcessUserId" int,
"ProcessUserName" nvarchar(100),
"OwnerUserName" nvarchar(100),
"UserStatus" nvarchar(5),
"CurrentStepRemarks" nvarchar(100),
"CurrentStep" int,
"StepStatus" nvarchar(50),
"DocumentStatus" nvarchar(50),
"CurrentStatus" nvarchar(50)

);

create local temporary table #tempPagingApproval(
"RowNum" int,
"WddCode" int,
"WtmCode" int,
"WtmName" nvarchar(100),
"CardCode" nvarchar(15),
"CardName" nvarchar(100),
"OwnerId" int,
"DocNo" nvarchar(50),
"ObjType" int,
"DocType" nvarchar(100),
"DocDate" datetime,
"DocDueDate" datetime,
"DocTotal" decimal(19,6),
"DocCur" varchar(10),
"IsDraft" char(1),
"UserId" int,
"UserCode" varchar(10),
"UserName" nvarchar(50),
"UpdateDate" datetime,
"UpdateTime" int,
"Status" char(1),
"Remarks" nclob,
"RequestType" char(1),--dùng để phân biệt my request và approval request
"ItemCheck" varchar(5),
"ProcesStat" varchar(5),
"StatusName" nvarchar(100),
"ProcessUserId" int,
"ProcessUserName" nvarchar(100),
"OwnerUserName" nvarchar(100),
"UserStatus" nvarchar(5),
"CurrentStepRemarks" nvarchar(100),
"CurrentStep" int,
"StepStatus" nvarchar(50),
"DocumentStatus" nvarchar(50),
"CurrentStatus" nvarchar(50)
);

insert into #tempApproval select a.*,b."Name" as "StatusName",
			ifnull((select FIRST_VALUE("UserID" order by "WddCode") "UserID" from WDD1 where "WddCode" = a."WddCode" and "Status"='W' and "UserID" = :userId),
			Ifnull((select FIRST_VALUE("UserID" order by "WddCode") "UserID" from WDD1 where "WddCode" = a."WddCode" and "Status"='W'),
			(select FIRST_VALUE("UserID" order by "SortId" desc) "UserID" from WDD1 where "WddCode" = a."WddCode"))) as "ProcessUserId",
			(select "U_NAME" from OUSR
			where "USERID" =
			ifnull((select FIRST_VALUE("UserID" order by "WddCode") "UserID" from WDD1 where "WddCode" = a."WddCode" and "Status"='W' and "UserID" = :userId),
			Ifnull((select FIRST_VALUE("UserID" order by "WddCode") "UserID" from WDD1 where "WddCode" = a."WddCode" and "Status"='W'),
			(select FIRST_VALUE("UserID" order by "SortId" desc) "UserID" from WDD1 where "WddCode" = a."WddCode")))) as "ProcessUserName",
			c.U_NAME "OwnerUserName",
			-- user status
			(select FIRST_VALUE("Status" order by "SortId" desc) "Status"
			from WDD1 where "WddCode" = a."WddCode" and "UserID" = :userId) "UserStatus",
			-- current step remarks
			(select FIRST_VALUE("Remarks" order by "SortId" desc) "Remarks"
			from WTM2 where "WtmCode" = a."WtmCode" and "WstCode" = 
			(select FIRST_VALUE("StepCode" order by "SortId" desc) "WstCode" from WDD1 where "WddCode" = a."WddCode")) "CurrentStepRemarks",
            (select FIRST_VALUE("StepCode" order by "SortId" desc) "WstCode" from WDD1 where "WddCode" = a."WddCode") "CurrentStep",
			-- step status
			(select case when (select count(*) from WDD1 t1 where t1."SortId" = (
			select FIRST_VALUE("SortId" order by "SortId" desc) "SortId"
			from WDD1 where "WddCode" = a."WddCode" and "UserID" = :userId)
			and t1."Status" = 'Y' and t1."WddCode" = a."WddCode") 
			>= (select "MaxReqr" from OWST where "WstCode" = 
			(select FIRST_VALUE("StepCode" order by "SortId" desc) "StepCode" 
			from WDD1 where "WddCode" = a."WddCode" and "UserID" = :userId))
			then 'Y'
			when (select count(*) from WDD1 t1 where t1."SortId" = 
			(select FIRST_VALUE("SortId" order by "SortId" desc) "SortId"
			from WDD1 where "WddCode" = a."WddCode" and "UserID" = :userId)
			and t1."Status" = 'N' and t1."WddCode" = a."WddCode") 
			>= (select "MaxRejReqr" from OWST where "WstCode" = 
			(select FIRST_VALUE("StepCode" order by "SortId" desc) "StepCode"
			from WDD1 where "WddCode" = a."WddCode" and "UserID" = :userId))
			then 'N' else 'W' end from dummy) "StepStatus"
			from #tmpApproval a
			left join :tblStatus b on a."Status" = b."Status"
			left join OUSR c on a."OwnerId" = c.USERID
			where (:fromDate is null or a."DocDate" >= to_date(:fromDate, 'yyyy-MM-dd'))
			and (:toDate is null or a."DocDate" <= to_date(:toDate, 'yyyy-MM-dd'))
			and a."ObjType" = :objType
			and ((:searchText = '' or :searchText is null) or (cast(a."WddCode" as nvarchar) = :searchText or cast(a."DocNo" as nvarchar) like '%' || :searchText || '%' or a."UserName" like N'%'|| :searchText || '%' or a."Remarks" like N'%'||:searchText || '%'))
			and ((:wddCode = -1 OR ifnull(:wddCode,0) = 0) or (a."WddCode" = :wddCode));
			
			
		insert into #tempFilterApproval 
		select Approval.*, Approval."ProcesStat" as "DocumentStatus", 
		case when Approval."ProcesStat" <> 'W' then Approval."ProcesStat" 
		when Approval."StepStatus" <> 'W' then Approval."StepStatus" 
		else Approval."UserStatus" end as "CurrentStatus"
		from #tempApproval Approval;
		
		insert into #tempPagingApproval
		select ROW_NUMBER() OVER (ORDER BY FilterApproval."WddCode" desc) "RowNum" ,FilterApproval.*
		from #tempFilterApproval FilterApproval where 
		((:typeFilter = 'A') 
		or (:typeFilter = 'Y' and FilterApproval."CurrentStatus"  in ('Y','A','P')) 
		or (:typeFilter = 'N' and FilterApproval."CurrentStatus" in ('W')) 
		or (:typeFilter = 'C' and FilterApproval."CurrentStatus" in ('-','C','N')));
		
		select * from #tempPagingApproval PagingApproval where (:pageIndex = -1 or (PagingApproval."RowNum" > :lowLimit AND PagingApproval."RowNum" <=:upLimit));

END