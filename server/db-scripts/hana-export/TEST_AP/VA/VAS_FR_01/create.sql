CREATE procedure VAS_FR_01 (
	in ReportCode		nvarchar(20), 
	in fdate			timestamp,
	in tdate			timestamp, 
	in LastPeriodType	char(1), -- Kỳ trước: 0/1: Kỳ liền trước/Kỳ này năm trước
	in includeJV		char(1), -- C/K: Có/Không
	in ContentDisplay	char(1), --I/A: Items/Accounts
	in ResultDisplay	char(1), -- Hiển thị bảng kết quả: Y-Yes; N-No
	in cur				nvarchar(10),
	in branch			int
)
as
begin
	declare maxJENum, monDiff, idx, idmax, CLidx, CLidmax int;
	declare lastfdate, lasttdate timestamp;
	declare account, calstr, calstr2 nvarchar(1000);
	declare sspace nvarchar(30);

	select a."AutoKey" into maxJENum from ONNM a where a."ObjectCode" = '30';
	call VAS_999 (tNo=>maxJENum,display=>0);
	
	if (LastPeriodType = '1') then
		lastfdate = ADD_YEARS(fdate,-1);
		lasttdate = ADD_YEARS(tdate,-1);
	else
		monDiff = MONTHS_BETWEEN(fdate,tdate) + 1;
		lastfdate = ADD_MONTHS(fdate,-monDiff);
		lasttdate = ADD_DAYS(fdate,-1);
	end if;
	
	create local temporary table #tbl (
		CompName		nvarchar(300),
		CompAddr		nvarchar(300),
		RptName			nvarchar(300),
		RptNote			nvarchar(100),
		PeriodTitle		nvarchar(300),
		CreatedTitle	nvarchar(300),
		Creator			nvarchar(100),
		Reviewer		nvarchar(100),
		ChiefActnt		nvarchar(100),
		ID				int not null primary key generated by default as IDENTITY,
		RptIDX			int,
		GrpCode			nvarchar(30) default 'I',
		Ord				int,
		ItmCode			nvarchar(30),
		ItmNote			nvarchar(300),
		MS				nvarchar(10),
		TM				nvarchar(20), 
		OBAmt			numeric(21,6),
		EBAmt			numeric(21,6),
		RoundNumber		int,
		CalLevel		int,
		FatherNum		nvarchar(30),
		ItmLevel		int,
		ItmType			nvarchar(20),
		ItmFormula		nvarchar(1000),
		ObjDetail		nvarchar(100),
		Font			nvarchar(20),
		FontStyle		nvarchar(30),
		FontUnderLine	char(1),
		FontSize		numeric(21,6),
		FontColor		nvarchar(20),
		FontC1			int,
		FontC2			int,
		FontC3			int,
		Display			char(1),
		Temp			char(1),
		HAlign			nvarchar(50),
		VAlign			nvarchar(50),
		FHide			char(1),
		SHide			char(1),
		OBNote			nvarchar(50) default N'Kỳ trước',
		EBNote			nvarchar(50) default N'Kỳ này',
		Note			nvarchar(100)
	);
	
	insert into #tbl (Ord, RptIDX, ItmCode, ItmNote, FatherNum, ItmType, ItmFormula, ItmLevel, Font, FontStyle, FontUnderLine, FontSize, FontColor, Display, MS, TM, ObjDetail, RoundNumber, CalLevel, Temp, HAlign, VAlign, FHide, SHide)
	select
		"VisOrder",
		ROW_NUMBER() OVER (ORDER BY "VisOrder"),
		"IndCode",
		"IndName",
		"FathCode",
		"Caculation",
		"Formula",
		"Level",
		"Font",
		"Type",
		"UnderLine",
		"Size",
		"Color",
		"Display",
		"Code",
		"Comments",
		"Detail",
		IFNULL("Round",0),
		"CLevel",
		"Temp",
		"HAlign",
		"VAlign",
		'',
		''
	from APZ_ARTI
	where "RepCode" = ReportCode;

	create local temporary table #DETAIL_0 (
		"TCode"			nvarchar(20),
		"Account"		nvarchar(254),
		"BPCode"		nvarchar(254),
		"Dim1"			nvarchar(254),
		"Dim2"			nvarchar(254),
		"Dim3"			nvarchar(254),
		"Dim4"			nvarchar(254),
		"Dim5"			nvarchar(254),
		"Project"		nvarchar(254),
		"RecipAccount"	nvarchar(254),
		"RecipBP"		nvarchar(254),
		"RecipDim1"		nvarchar(254),
		"RecipDim2"		nvarchar(254),
		"RecipDim3"		nvarchar(254),
		"RecipDim4"		nvarchar(254),
		"RecipDim5"		nvarchar(254),
		"RecipProject"	nvarchar(254),
		"CalMth"		nvarchar(10),
		"RepCode"		nvarchar(20) NOT NULL,
		"Code"			nvarchar(20),
		"IndCode"		nvarchar(20) NOT NULL,
		"SoEoP"			nvarchar(20),
		"Note"			nvarchar(254),
		"Currency"		nvarchar(3),
		"Round"			int,
		"LValue1"		numeric(21,6),
		"LValue2"		numeric(21,6),
		"LValue3"		numeric(21,6),
		"LValue4"		numeric(21,6),
		"LValue5"		numeric(21,6),
		"LValue6"		numeric(21,6),
		"LValue7"		numeric(21,6),
		"IndName"		nvarchar(254),
		"Sign"			int,
		"UDate"			timestamp,
		"COrder"		int,
		"CInactive"		char(1),
		"Detail"		nvarchar(254),
		"OBAmt"			numeric(21,6),
		"EBAmt"			numeric(21,6),
		"ID"			int
	);
	
	insert into #DETAIL_0 (
		"TCode", "Account", "BPCode", "Dim1", "Dim2", "Dim3", "Dim4", "Dim5", "Project", "RecipAccount", "RecipBP",
		"RecipDim1", "RecipDim2", "RecipDim3", "RecipDim4", "RecipDim5", "RecipProject", "CalMth",
		"RepCode", "Code", "IndCode", "SoEoP", "Note", "Currency", "Round",
		"LValue1", "LValue2", "LValue3", "LValue4", "LValue5", "LValue6", "LValue7",
		"IndName", "Sign", "UDate", "COrder", "CInactive",
		"Detail", "OBAmt", "EBAmt", "ID")
	select
		a."TCode", a."Account", a."BPCode", a."Dim1", a."Dim2", a."Dim3", a."Dim4", a."Dim5", a."Project", a."RecipAccount", a."RecipBP",
		a."RecipDim1", a."RecipDim2", a."RecipDim3", a."RecipDim4", a."RecipDim5",
		a."RecipProject", a."CalMth", a."RepCode", a."Code", a."IndCode", a."SoEoP", a."Note", a."Currency", a."Round",
		a."LValue1", a."LValue2", a."LValue3", a."LValue4", a."LValue5", a."LValue6", a."LValue7",
		a."IndName", a."Sign", a."UDate", a."COrder", a."CInactive",
		b."Detail", 0, 0, ROW_NUMBER() OVER (ORDER BY b."VisOrder")
	from APZ_ARTA a, APZ_ARTI b
	where a."RepCode" = ReportCode and a."RepCode" = b."RepCode" and a."IndCode" = b."IndCode";
	
	update #DETAIL_0 set "RecipAccount" = '*' where "RecipAccount" is null;
	
	update #DETAIL_0 set
		"BPCode"		= IFNULL("BPCode",''),
		"Dim1"			= IFNULL("Dim1",''),
		"Dim2"			= IFNULL("Dim2",''),
		"Dim3"			= IFNULL("Dim3",''),
		"Dim4"			= IFNULL("Dim4",''),
		"Dim5"			= IFNULL("Dim5",''),
		"Project"		= IFNULL("Project",''),
		"RecipAccount"	= IFNULL("RecipAccount",''),
		"RecipBP"		= IFNULL("RecipBP",''),
		"RecipDim1"		= IFNULL("RecipDim1",''),
		"RecipDim2"		= IFNULL("RecipDim2",''),
		"RecipDim3"		= IFNULL("RecipDim3",''),
		"RecipDim4"		= IFNULL("RecipDim4",''),
		"RecipDim5"		= IFNULL("RecipDim5",''),
		"RecipProject"	= IFNULL("RecipProject",'');
		
	update #DETAIL_0 set
		"Account"		= REPLACE("Account",';',','),
		"BPCode"		= REPLACE("BPCode",';',','),
		"Dim1"			= REPLACE("Dim1",';',','),
		"Dim2"			= REPLACE("Dim2",';',','),
		"Dim3"			= REPLACE("Dim3",';',','),
		"Dim4"			= REPLACE("Dim4",';',','),
		"Dim5"			= REPLACE("Dim5",';',','),
		"Project"		= REPLACE("Project",';',','),
		"RecipAccount"	= REPLACE("RecipAccount",';',','),
		"RecipBP"		= REPLACE("RecipBP",';',','),
		"RecipDim1"		= REPLACE("RecipDim1",';',','),
		"RecipDim2"		= REPLACE("RecipDim2",';',','),
		"RecipDim3"		= REPLACE("RecipDim3",';',','),
		"RecipDim4"		= REPLACE("RecipDim4",';',','),
		"RecipDim5"		= REPLACE("RecipDim5",';',','),
		"RecipProject"	= REPLACE("RecipProject",';',',');
		
	create local temporary table #DETAIL (
		IDX				int not null primary key generated by default as IDENTITY,
		IndID			int,
		Account			nvarchar(1000),
		BPCode			nvarchar(1000),
		Dim1			nvarchar(1000),
		Dim2			nvarchar(1000),
		Dim3			nvarchar(1000),
		Dim4			nvarchar(1000),
		Dim5			nvarchar(1000),
		Project			nvarchar(1000),
		RecipAccount	nvarchar(1000),
		RecipBP			nvarchar(1000),
		RecipDim1		nvarchar(1000),
		RecipDim2		nvarchar(1000),
		RecipDim3		nvarchar(1000),
		RecipDim4		nvarchar(1000),
		RecipDim5		nvarchar(1000),
		RecipProject	nvarchar(1000),
		CalMth			nvarchar(10),
		PLTO			nvarchar(10),
		RepCode			nvarchar(50),
		ColName			nvarchar(100),
		IndCode			nvarchar(50),
		Detail			nvarchar(100),
		OBAmt			numeric(21,6),
		EBAmt			numeric(21,6),
		ID				int,
		Currency		nvarchar(10),
		SoEoP			nvarchar(10),
		SignCal			int
	);

	if (ContentDisplay = 'A') then
		idx = 1;
		
		while (idx <= (select MAX(ID) from #DETAIL_0))
		do
			select "Account" into account from #DETAIL_0 where "ID" = idx;
			
			listChildAcc = select * from getListChildAccount(account);
			
			insert into #DETAIL (Account, BPCode, Dim1, Dim2, Dim3, Dim4, Dim5, Project, RecipAccount, RecipBP, RecipDim1, RecipDim2, RecipDim3, RecipDim4, RecipDim5, RecipProject, CalMth, PLTO, RepCode, ColName, IndCode, Detail, OBAmt, EBAmt, ID, Currency, SoEoP, SignCal)
			select
				c."AcctCode",
				a."BPCode",
				a."Dim1",
				a."Dim2",
				a."Dim3",
				a."Dim4",
				a."Dim5",
				a."Project",
				a."RecipAccount",
				a."RecipBP",
				a."RecipDim1",
				a."RecipDim2",
				a."RecipDim3",
				a."RecipDim4",
				a."RecipDim5",
				a."RecipProject",
				a."CalMth",
				'',
				a."RepCode",
				'',
				a."IndCode",
				a."Detail",
				a."OBAmt",
				a."EBAmt",
				a."ID",
				a."Currency",
				a."SoEoP",
				a."Sign"
			from #DETAIL_0 a, :listChildAcc b, OACT c
			where
				a."ID" = idx
				and b.Data = c."AcctCode"
				and c."Postable" = 'Y';
			
			idx = idx + 1;
		end while;
	elseif (ContentDisplay = 'I') then
		insert into #DETAIL (IndID, Account, BPCode, Dim1, Dim2, Dim3, Dim4, Dim5, Project, RecipAccount, RecipBP, RecipDim1, RecipDim2, RecipDim3, RecipDim4, RecipDim5, RecipProject, CalMth, PLTO, RepCode, ColName, IndCode, Detail, OBAmt, EBAmt, ID, Currency, SoEoP, SignCal)
		select
			a."ID",
			a."Account",
			a."BPCode",
			a."Dim1",
			a."Dim2",
			a."Dim3",
			a."Dim4",
			a."Dim5",
			a."Project",
			a."RecipAccount",
			a."RecipBP",
			a."RecipDim1",
			a."RecipDim2",
			a."RecipDim3",
			a."RecipDim4",
			a."RecipDim5",
			a."RecipProject",
			a."CalMth",
			'',
			a."RepCode",
			'',
			a."IndCode",
			a."Detail",
			a."OBAmt",
			a."EBAmt",
			a."ID",
			a."Currency",
			a."SoEoP",
			a."Sign"
		from #DETAIL_0 a;
	end if;
	
	idx = 1;
	
	
	update #DETAIL set
		OBAmt	= getTransactionSC(fdate=>lastfdate,tdate=>lasttdate,acc=>Account,bp=>BPCode,dim1=>Dim1,dim2=>Dim2,dim3=>Dim3,dim4=>Dim4,dim5=>Dim5,prj=>Project,ofsacc=>RecipAccount,ofsbp=>RecipBP,ofsdim1=>RecipDim1,ofsdim2=>RecipDim2,ofsdim3=>RecipDim3,ofsdim4=>RecipDim4,ofsdim5=>RecipDim5,ofsprj=>RecipProject,method=>CalMth,ObjTypelist=>Detail,ttype=>PLTO,includeJV=>includeJV,curr=>cur,OBorEB=>SoEoP,signCal=>SignCal,branch=>branch),
		EBAmt	= getTransactionSC(fdate=>fdate,tdate=>tdate,acc=>Account,bp=>BPCode,dim1=>Dim1,dim2=>Dim2,dim3=>Dim3,dim4=>Dim4,dim5=>Dim5,prj=>Project,ofsacc=>RecipAccount,ofsbp=>RecipBP,ofsdim1=>RecipDim1,ofsdim2=>RecipDim2,ofsdim3=>RecipDim3,ofsdim4=>RecipDim4,ofsdim5=>RecipDim5,ofsprj=>RecipProject,method=>CalMth,ObjTypelist=>Detail,ttype=>PLTO,includeJV=>includeJV,curr=>cur,OBorEB=>SoEoP,signCal=>SignCal,branch=>branch);
	
	update #tbl set OBAmt = IFNULL((select sum(x.OBAmt) from #DETAIL x where x.IndCode = #tbl.ItmCode),0);
	update #tbl set EBAmt = IFNULL((select sum(x.EBAmt) from #DETAIL x where x.IndCode = #tbl.ItmCode),0);
		

	update #tbl set CalLevel = 10000 where CalLevel is null;
			
	select MIN(CalLevel), MAX(CalLevel)
	into CLidx, CLidmax
	from #tbl
	where UPPER(ItmType) in ('SUBTOTAL','FORMULA');
	
	while (CLidx <= CLidmax) do
		update #tbl set
			OBAmt = (select SUM(x.OBAmt) from #tbl x where x.FatherNum = #tbl.ItmCode),
			EBAmt = (select SUM(x.EBAmt) from #tbl x where x.FatherNum = #tbl.ItmCode)
		where CalLevel = :CLidx and UPPER(ItmType) = 'SUBTOTAL';
	
		update #tbl set OBAmt = IFNULL(OBAmt,0), EBAmt = IFNULL(EBAmt,0);
		
		select MIN(ID), MAX(ID)
		into idx, idmax
		from #tbl
		where UPPER(ItmType) = 'FORMULA' and CalLevel = :CLidx;
		
		while (idx <= idmax) do

			if exists(select 1 from #tbl where ID = :idx and UPPER(ItmType) = 'FORMULA' and CalLevel = :CLidx) then
				declare idxStr nvarchar(20);
				declare fIdx, fIdxMax int;
				
				idxStr = idx;
				
				select ItmFormula into calstr from #tbl where ID = :idx;
				
				Tmp_Param1 =
					select ROW_NUMBER() OVER (ORDER BY "DATA") ID, REPLACE(LEFT("DATA",LOCATE("DATA",']')),']','') Name
					from Split(calstr,'[')
					where IFNULL("DATA",'') <> '';
				
				select 1, MAX(ID)
				into fIdx, fIdxMax
				from :Tmp_Param1;
				
				select calstr
				into calstr2
				from dummy;
				
				while (fIdx <= fIdxMax) do
					if (select count(1) from #tbl x, :Tmp_Param1 y where x.ItmCode = y.Name and y.ID = :fIdx)>0 then 
						select REPLACE(calstr,'[' || x.ItmCode || ']','(' || cast(x.OBAmt as varchar) || ')'), REPLACE(calstr2,'[' || x.ItmCode || ']','(' || cast(x.EBAmt as varchar) || ')')
						into calstr, calstr2
						from #tbl x, :Tmp_Param1 y
						where x.ItmCode = y.Name and y.ID = :fIdx;
					end if;
					fIdx = fIdx + 1;
				end while;
				
				if (LOCATE(calstr,'[') > 0 or calstr = '') then
					calstr = '0';
				end if;
				
				if (LOCATE(calstr2,'[') > 0 or calstr2 = '') then
					calstr2 = '0';
				end if;
				
				if (IFNULL(calstr,'') <> '' and IFNULL(idxStr,'') <> '') then
					execute immediate 'update #tbl set OBAmt = ' || calstr || ' where ID = ' || idxStr;
				end if;
				
				if (IFNULL(calstr2,'') <> '' and IFNULL(idxStr,'') <> '') then
					execute immediate 'update #tbl set EBAmt = ' || calstr2 || ' where ID = ' || idxStr;
				end if;

				
			end if;
			
			calstr = '';
			
			idx = idx + 1;
		end while;
			
		CLidx = CLidx + 1;
	end while;

	idx = 2;
	sspace = '';
	while (idx <= (select MAX(ItmLevel) from #tbl)) do
		update #tbl set ItmNote = sspace || ItmNote where ItmLevel = :idx;
		sspace = sspace || '  ';
		idx = idx + 1;
	end while;
	
	if (LastPeriodType = '1') then
		update #tbl set EBNote = N'Kỳ này' || CHAR(13) || CHAR(10) || N'năm nay', OBNote = N'Kỳ này' || CHAR(13) || CHAR(10) || N'năm trước';
	end if;
	
	update x set CompName = y."CompnyName", CompAddr = y."CompnyAddr", RptName = N'', PeriodTitle = N'Từ ngày ' || TO_VARCHAR(fdate,'dd/MM/yyyy') || N' đến ngày ' || TO_VARCHAR(tdate,'dd/MM/yyyy'), CreatedTitle = N'Lập ngày ..... tháng ..... năm ..........'
	from #tbl x, OADM y;
	
	update x set RptName = y."RepName" from #tbl x, APZ_ART y where y."RepCode" = ReportCode;

	
	Tmp_OADM =
		select "DecSep", "ThousSep"
		from OADM;

	Tmp_PID =
		select 'PID' as PID
		from dummy;
	
	create local temporary table #tbl_detail (
		IndCode		nvarchar(30),
		IndID		int,
		Account		nvarchar(1000),
		AccountName	nvarchar(100),
		D_OBAmt		numeric(21,6),
		D_EBAmt		numeric(21,6)
	);

	insert into #tbl_detail (IndCode, IndID, Account, AccountName, D_OBAmt, D_EBAmt)
	select IndCode, IndID, Account, cast('' as nvarchar(100)) AccountName, OBAmt, EBAmt
	from #DETAIL;
	
	update x set AccountName = y."AcctName" from #tbl_detail x, OACT y where x.Account = y."AcctCode";

	if (ResultDisplay = 'Y' and ContentDisplay = 'I') then
		truncate table #tbl_detail;
	end if;
	
	if (ResultDisplay = 'Y') then
		select *
		from
			#tbl a
			left join :tmp_OADM a1 on 1 = 1
			left join :tmp_PID a2 on 1 = 1
			left join #tbl_detail b on a.ItmCode = b.IndCode
		where IFNULL(a.Display,'Y') = 'Y'
		order by RptIDX;
	end if;

	drop table #tbl;
	drop table #DETAIL;
	drop table #DETAIL_0;
	drop table #tbl_detail;
end

