		insert into #tblBALANCE (AcctCode,OffsetAcct,Bal)
		values ('1549', '6325', Bal1549);		
	end if;
	*/
		
		-- Phát sinh Có
		insert into #tbl (RefDate, AcctCode,Debit,Credit,LineID)
		select tdate,AcctCode,0,Bal,ID from #tblBALANCE where AcctCode = '1548';
		
		-- Phát sinh Nợ
		insert into #tbl (RefDate, AcctCode,Debit,Credit,LineID)
		select tdate,OffsetAcct,Bal,0,ID from #tblBALANCE where AcctCode = '1548';
	
		--Đảo hạch toán nếu âm
		update #tbl set Debit = -(Credit), Credit = 0 where Credit < 0;
		update #tbl set Debit = 0, Credit = -(Debit) where Debit < 0;	
		
	 
		select RefDate as "RefDate", AcctCode as "AcctCode",
			cast(Debit as decimal(28,2)) as "Debit",
		   cast(Credit as decimal(28,2)) as "Credit",
		  --Project as "Project",
		  --ProfitCode as "ProfitCode", 
		   --OcrCode2 as "OcrCode2", 
		   --OcrCode3 as "OcrCode3", OcrCode4 as "OcrCode4", OcrCode5 as "OcrCode5",
		   GroupKey as "GroupKey" from #tbl where Debit<>0 or Credit<>0 order by GroupKey,GroupID,LineID;
		
		drop table #tbl;
		drop table #tbl1548;
		drop table #tblBALANCE;
	END IF;
end
