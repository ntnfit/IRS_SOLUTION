	from #tbl1549 x left join OWOR y on y."ObjType" = x.TransType and y."DocEntry" = x.CreatedBy
					left join OITM z on z."ItemCode" = y."ItemCode";
	
	insert into #tblBALANCE (AcctCode,OffsetAcct,Bal)
	select AcctCode,OffsetAcct, sum(Bal)
	from #tbl1549
	group by AcctCode,OffsetAcct;
	
	select	
		ifnull((select sum("Debit"-"Credit") from "JDT1" where ("Account" like '62%' or ("Account" in ('1541', '1542'))) and "RefDate" between fdate and tdate),0)
		+
		ifnull((select sum("Debit"-"Credit") from "JDT1" where "Account" = '1549' and "RefDate" between fdate and tdate and "TransType" = 162),0)
