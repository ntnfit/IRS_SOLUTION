Create procedure USP_PROD_COSTING_CLSEXP_Bkup (
	in period 	nvarchar(20), 
	in PrdLine 	nvarchar(1000), 
	in branch 	int
)
as
begin
	declare fdate,tdate date;
	declare Bal1548 decimal(28, 10) = 0;
	select "F_RefDate","T_RefDate" into fdate,tdate from "OFPR" where "Code"=period;
	if (TO_DATE(tdate,'YYYY-MM-DD') > TO_DATE(current_date,'YYYY-MM-DD')) then
		tdate = current_date;
	end if;
	--======================================================
	IF (select count(1) from  OJDT where "Memo" = 'Transfer manufacturing cost in ' || right (period,2) ||'/'|| left (period,4))>0 then
		select 'Đã thực hiện kết chuyển' from dummy;
	ElseIf (select count(1) from "@COSTING_H" a ,"@COSTING_L3" b where a."DocEntry"  =b."DocEntry" and "U_Period"=period)>0 then -- lay du lieu UDO
		--================ lay du lieu tu UDO COSTING 
			--trường hợp này là do chạy costing ngoài giờ hỗ trợ, nên tạo udo này để iLD có thể chủ động copy paste dữ liệu vào 
		select "U_RefDate" as  "RefDate",
				"U_AcctCode" as  "AcctCode",
				"U_Debit" as  "Debit",
				"U_Credit" as  "Credit",
				"U_GroupKey" as  "GroupKey"
		from "@COSTING_H" a
		inner join "@COSTING_L3" b on a."DocEntry"  = b."DocEntry" and a."U_Period" = :period and a."Canceled" = 'N'
		order by "LineId"; 
	--
	
	ELSE

		create local temporary table #tbl (
			ID 			int not null primary key generated by default as IDENTITY,
			RefDate		date,
			AcctCode 	nvarchar(20), 
			Debit 		numeric(28,10), 
			Credit 		numeric(28,10),
			ProfitCode 	nvarchar(20),
			OcrCode2 	nvarchar(20),
			OcrCode3 	nvarchar(20),
			OcrCode4 	nvarchar(20),
			OcrCode5 	nvarchar(20),
			Project 	nvarchar(20), 
			GroupKey 	nvarchar(20) default '1',
			GroupID 	int default 1,
			LineID		int
		);
		create local temporary table #tblBALANCE (
			ID 			int not null primary key generated by default as IDENTITY,
			AcctCode	nvarchar(20),
			OffsetAcct	nvarchar(20),
			Bal			numeric(28,10)
		);
		create local temporary table #tbl1548 (
			ID 			int not null primary key generated by default as IDENTITY,
			AcctCode	nvarchar(20),
			OffsetAcct	nvarchar(20),
			TransId		int,
			CreatedBy	int,
			TransType	int,
			Bal			numeric(28,10),
			ItemCode	nvarchar(50),
			ItemGroup	int
		);
		
		insert into #tblBALANCE (AcctCode,Bal)
		select "Account", sum("Debit"-"Credit") 
		from "JDT1" 
		where ("Account" like '62%' or ("Account" in ('1541', '1542','1546','1547','154501', '154503', '154509'))) 
			and "RefDate" between fdate and tdate 
		group by "Account" 
		having sum("Debit"-"Credit") <> 0 
		order by "Account";
		
		
	
		-- Phát sinh Có
		insert into #tbl (RefDate, AcctCode,Debit,Credit,LineID)
		select tdate,AcctCode,0,Bal,ID from #tblBALANCE;
		
	
		-- Phát sinh Nợ
		insert into #tbl (RefDate, AcctCode,Debit,Credit,LineID)
		select tdate,'1548',Bal,0,ID from #tblBALANCE;
		
	   /*
	--Chuyển số dư 1549 về 632 do Total Variance của SAP sinh ra trong Production Order
	insert into #tbl1549 (AcctCode, TransId, CreatedBy, TransType, Bal)
	select "Account", "TransId", "CreatedBy", "TransType", sum("Debit"-"Credit")
	from "JDT1"
	where "Account" = '1549' and "RefDate" between fdate and tdate and "TransType" <> 162
	group by "Account", "TransId", "CreatedBy", "TransType"
	having sum("Debit"-"Credit") <> 0;

