CREATE procedure VAS_F_PO_04 (
	in DocID	int
)
as
begin
	declare bplID int;
	declare DecQty, DecPrice int;
	declare DateSep, ThousSep nvarchar(10);
	declare num1, num2 numeric(21,6);
	
	select ifnull(x."BPLId",0) into bplID from "OPOR" x where x."DocEntry"=DocId;
	----------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tbl (
		CompName 			nvarchar(200)
		, CompAddr 			nvarchar(300)
		, Phone				nvarchar(40)
		, Fax 				nvarchar(40)
		, TaxIdNum 			nvarchar(64)
		, RptName 			nvarchar(500)
		, DocNum 			int
		, DocDate 			timestamp
		, Cardcode 			nvarchar(30)
		, Cardname 			nvarchar (200)
		, AddrCard 			nvarchar(500)
		, J_Number 			nvarchar(508)
		, ItemCode 			nvarchar(40)
		, ItemName 			nvarchar(200)
		, Dscription 		nvarchar(200)						
		, BuyUnitMsr 		nvarchar(200)
		, ItemGroupCode  	int
		, ItemGroupName 	nvarchar(40)
		, RequestDept 		nvarchar(100)
		, WhsCode 			nvarchar(16)
		, WhsName 			nvarchar(200)
		, ReceiDate 		timestamp
		, Quantity 			numeric(21,6)
		, Price 			numeric(21,6)
		, LineTotal 		numeric(21,6)
		, Remark 			nvarchar(1000)
		, U_Dept 			nvarchar(20)
		, DocCur 			nvarchar(6)
		, ID 				int not null primary key generated by default as IDENTITY
		, Comments 			nvarchar(254)
		, Freight 			numeric(21,6)
		, DocTotal 			numeric(21,6)
		, LineStatus 		nvarchar(3)
		, VATSum 			numeric(21,6)
		, PayTerm 			nvarchar(100)
		, UserCreat 		nvarchar(30)
		, PrntDate 			timestamp
		, Department 		nvarchar(50)
	);
	-- REPORT ----------------------------------------------------------------------------------------------------------------

	
	INSERT INTO #tbl (Docdate, DocNum, DocCur, Cardcode, Cardname, AddrCard, J_Number,ItemCode, ItemName, Dscription, BuyUnitMsr, ItemGroupCode, WhsCode, WhsName, Quantity, Price, LineTotal, U_Dept, ReceiDate, Remark ,Comments, Freight, DocTotal, LineStatus, VATSum, UserCreat, PrntDate, PayTerm, Department)
	SELECT
		a."DocDate",a."DocNum",a."DocCur",a."CardCode",a."CardName",a."Address",a."U_JVNumber",b."ItemCode",b."Dscription",b."Dscription",b."unitMsr" 
		,(Select x."ItmsGrpCod" from "OITM" x where x."ItemCode" = b."ItemCode") ItmsGrpCode
		,b."WhsCode"
		,(select y."WhsName" from "OWHS" y where y."WhsCode" = b."WhsCode") whsName
		,b."Quantity"
		,b."Price"
		,(Case when a."DocCur" ='VND' then b."LineTotal" else b."TotalFrgn" end)
		,''
		,b."ShipDate"
		,''--a."Comments"
		,a."Comments"
		,ifnull((select case ifnull(a."DocCur",'VND') when 'VND' then SUM(z."LineTotal") else SUM(z."TotalFrgn") end from "POR3" z where z."DocEntry" = a."DocEntry"),0)
		,case IFNULL(a."DocCur",'VND') when 'VND' then a."DocTotal" else a."DocTotalFC" end
		,b."LineStatus"
		,case IFNULL(a."DocCur",'VND') when 'VND' then IFNULL(a."VatSum",0) else IFNULL(a."VatSumFC",0) end
		,a."UserSign"
		,CURRENT_DATE
		,''
		, b."OcrCode3"
	FROM "OPOR" a , "POR1" b WHERE a."DocEntry" = b."DocEntry" and a."DocEntry" = DocID and (b."LineStatus" = 'O' or (b."LineStatus" = 'C' and b."LineTotal" > 0));
	
	update #tbl set ItemGroupName = (select x."ItmsGrpNam" from "OITB" x where x."ItmsGrpCod"=#tbl.ItemGroupCode);

	UPDATE #tbl set CompName = (Select UPPER("CompnyName") from "OADM")
					, CompAddr = CONCAT('Address: ',(Select MAX("Street") from "ADM1"))
					, Phone = (Select "Phone1" from "OADM")
					, Fax = (Select "Fax" from "OADM")
					, TaxIdNum = (Select "TaxIdNum" from "OADM")
					, RptName = N'PHIẾU ĐẶT HÀNG';

	update #tbl set UserCreat = (select "USER_CODE" from "OUSR" where "USERID" = #tbl.UserCreat);

		
	select 
		CompName "CompName",
		CompAddr "CompAddr",
		Phone "Phone",
		Fax "Fax",
		TaxIdNum "TaxIdNum",
		RptName "RptName",
		DocNum "DocNum",
		DocDate "DocDate",
		Cardcode "Cardcode",
		Cardname "Cardname",
		AddrCard "AddrCard",
		J_Number "J_Number",
		ItemCode "ItemCode",
		ItemName "ItemName",
		Dscription "Dscription",
		BuyUnitMsr "BuyUnitMsr",
		ItemGroupCode "ItemGroupCode",
		ItemGroupName "ItemGroupName",
		RequestDept "RequestDept",
		WhsCode "WhsCode",
		WhsName "WhsName",
		ReceiDate "ReceiDate",
		Quantity "Quantity",
		Price "Price",
		LineTotal "LineTotal",
		Remark "Remark",
		U_Dept "U_Dept",
		DocCur "DocCur",
		ID "ID",
		Comments "Comments",
		Freight "Freight",
		DocTotal "DocTotal",
		LineStatus "LineStatus",
		VATSum "VATSum",
		PayTerm "PayTerm",
		UserCreat "UserCreat",
		PrntDate "PrntDate",
		Department "Department"
	from #tbl;

	drop table #tbl;
end

