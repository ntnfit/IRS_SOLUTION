CREATE procedure Traceability_Solution_New
(
	in itemCode nvarchar(50),
	in batch nvarchar(36)	
)
as
begin

-- 	Lấy dữ liệu từ pro04: fdate,tdate,itemcode,warehouse,batch,DocNumPO,OutSoucing
	call USP_RPT_PROD_04 ('2019-01-01','2099-01-01','','','','','Y',tab_result);
	create local temporary table #pro04 as ( select WONO, ITEMCODE,BATCH, sum(QTY) as QTY  from $tab_result group by WONO, ITEMCODE,BATCH);
	--
	create local temporary table #tbl
	(
		Lvl			int,
		ID			int not null primary key generated by default as IDENTITY,
		PIID		int,
		BatchNum	nvarchar(50),
		ItemCode	nvarchar(50),
		ItemName	nvarchar(100),
		ItmsGrpCod	int,
		DocType		int,
		DocEntry	int,
		DocNum		int,
		Qty			numeric(21,6)
	); 
	
	/*Level 1*/
	insert into #tbl (Lvl, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 1, b."MnfSerial", a."ItemCode", c."ItemName", c."ItmsGrpCod", 202, a."BsDocEntry", d."DocNum", sum(a."Quantity")
	from IBT1 a join OWOR d on d."ObjType"=a."BsDocType" and d."DocEntry"=a."BsDocEntry"
	join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
	join OITM c on a."ItemCode"=c."ItemCode"
	where a."BaseType"=59 and b."MnfSerial" is not null and b."MnfSerial"=:batch and (ifnull(:itemCode,'')='' or a."ItemCode"=:itemCode) and c."ItmsGrpCod" in (120,121)
	group by a."ItemCode", c."ItemName", c."ItmsGrpCod", a."BsDocEntry", d."DocNum", b."MnfSerial";
	
	
	/* Level 2 */
	create local temporary table #temp (DocType int, DocEntry int, DocNum int, Qty decimal(21,6));
	
	insert into #temp (DocType, DocEntry, DocNum, Qty)
	select b.DocType, b.DocEntry, b.DocNum, sum(a."Quantity")
	from IBT1 a join #tbl b on a."BsDocType"=b.DocType and a."BsDocEntry"=b.DocEntry and a."BsDocLine"=-1
	group by b.DocType, b.DocEntry, b.DocNum;
	--
	
	/*
	insert into #temp (DocType, DocEntry, DocNum, Qty)
	select b.DocType, b.DocEntry, b.DocNum, sum(a."Quantity")
	from IBT1 a join #tbl b on a."BsDocType"=b.DocType and a."BsDocEntry"=b.DocEntry
	join WOR1 c on c."DocEntry"=b.DocEntry and c."LineNum"=a."BsDocLine"
	where c."PlannedQty"<0
	group by b.DocType, b.DocEntry, b.DocNum;
	*/
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 2, b.ID, '', '', '', b.ItmsGrpCod, a.DocType, a.DocEntry, a.DocNum, sum(a.Qty)
	from #temp a join #tbl b on a.DocType=b.DocType and a.DocEntry=b.DocEntry
	group by b.ID, b.ItmsGrpCod, a.DocType, a.DocEntry, a.DocNum;
	
	/*Level 3*/
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 3, b.ID, c."MnfSerial", a."ItemCode", d."ItemName", d."ItmsGrpCod", b.DocType, b.DocEntry, b.DocNum, sum(a."Quantity")
	from IBT1 a join #tbl b on a."BsDocType"=b.DocType and  a."BsDocEntry"=b.DocEntry
	join OBTN c on a."BatchNum"=c."DistNumber" and a."ItemCode"=c."ItemCode"
	join OITM d on a."ItemCode"=d."ItemCode"
	where a."BaseType"=60 and b.Lvl = 2
	group by b.ID, c."MnfSerial", a."ItemCode", d."ItemName", d."ItmsGrpCod", b.DocType, b.DocEntry, b.DocNum;
	
	/*Level 4*/
	-- Tổng batch NVL ban đầu nhập GRPO
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 4, d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, 20, a."BaseEntry", a."BaseNum", sum(a."Quantity")
	from IBT1 a join OPDN b on a."BaseType"=b."ObjType" and a."BaseEntry"=b."DocEntry"
	join OBTN c on c."DistNumber"=a."BatchNum" and c."ItemCode"=a."ItemCode"
	join #tbl d on d.Lvl=3 and d.ItemCode=a."ItemCode" and d.BatchNum=c."MnfSerial"
	where b.CANCELED='N' and d.ItmsGrpCod<>121-- NVL
	group by d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, a."BaseEntry", a."BaseNum";
	
	-- Tổng batch rework ban đầu nhập Receipt from PO
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 4, d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, 202, a."BsDocEntry", e."DocNum", sum(a."Quantity")
	from IBT1 a join OIGN b on a."BaseType"=b."ObjType" and a."BaseEntry"=b."DocEntry"
	join OBTN c on c."DistNumber"=a."BatchNum" and c."ItemCode"=a."ItemCode"
	join #tbl d on d.Lvl=3 and d.ItemCode=a."ItemCode" and d.BatchNum=c."MnfSerial"
	join OWOR e on e."ObjType"=a."BsDocType" and e."DocEntry"=a."BsDocEntry"
	where d.ItmsGrpCod=121 and a."BsDocEntry"<>d.DocEntry -- Group Thành phẩm-rework
	group by d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, a."BsDocEntry", e."DocNum";
	
	/*Level 5*/
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 5, b.ID, c."MnfSerial", a."ItemCode", d."ItemName", d."ItmsGrpCod", b.DocType, b.DocEntry, b.DocNum, sum(a."Quantity")
	from IBT1 a join #tbl b on b.Lvl=4 and b.ItmsGrpCod=121 and a."BsDocType"=b.DocType and a."BsDocEntry"=b.DocEntry
	join OBTN c on a."ItemCode"=c."ItemCode" and a."BatchNum"=c."DistNumber"
	join OITM d on a."ItemCode"=d."ItemCode"
	where a."BaseType"=60 and d."ItmsGrpCod"=113
	group by b.ID, c."MnfSerial", a."ItemCode", d."ItemName", d."ItmsGrpCod", b.DocType, b.DocEntry, b.DocNum;
	
	/*Level 6*/
	insert into #tbl (Lvl, PIID, BatchNum, ItemCode, ItemName, ItmsGrpCod, DocType, DocEntry, DocNum, Qty)
	select 6, d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, 20, a."BaseEntry", a."BaseNum", sum(a."Quantity")
	from IBT1 a join OPDN b on a."BaseType"=b."ObjType" and a."BaseEntry"=b."DocEntry"
	join OBTN c on a."ItemCode"=c."ItemCode" and a."BatchNum"=c."DistNumber"
	join #tbl d on d.Lvl=5 and d.BatchNum=c."MnfSerial" and d.ItemCode=c."ItemCode"
	join #tbl e on e.ID=d.PIID
	where b.CANCELED='N' and e.ItmsGrpCod=121
	group by d.ID, d.BatchNum, d.ItemCode, d.ItemName, d.ItmsGrpCod, a."BaseEntry", a."BaseNum";
	
	
	---
	update a
	set a.QTY  =   (select sum(QTY ) from  #pro04  where  a.DocNum =  WONO )
	from #tbl a
	WHERE a.LVL = 2;


--
	select * from #tbl;
	drop table #tbl;
	drop table #pro04;
	
end;

