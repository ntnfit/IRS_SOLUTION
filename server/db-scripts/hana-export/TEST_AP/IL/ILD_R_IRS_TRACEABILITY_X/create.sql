CREATE procedure ILD_R_IRS_Traceability_X 
(in itemCode nclob ,
 in batch nclob )
as
begin
-- 	Lấy dữ liệu từ pro04 fdate,tdate, itemcode, warehouse, batch, DocNumPO, OutSoucing
	call USP_RPT_PROD_04 ('2019-01-01','2099-01-01','','','','','Y',tab_result);
	create local temporary table #pro04 as ( select WONO,WOID, ITEMCODE,ITEMNAME,BATCH, sum(QTY) as QTY  from $tab_result group by WONO,WOID, ITEMCODE,ITEMNAME,BATCH);
	create local temporary table #tbl
	(
		ID int not null primary key generated by default as IDENTITY,
		ParentID int,
		ItemCode nvarchar(50),
		ItemName nvarchar(100),
		Batch nvarchar(50),
		Qty decimal(21,6),
		DocEntry int,
		DocType int,
		DocNum varchar(200),
		Lvl int
	);
	
	/* Level 1 */
	insert into #tbl (ItemCode, ItemName, Batch, Qty, DocEntry, DocType, DocNum, Lvl)
	select a."ItemCode", c."ItemName", b."MnfSerial", sum(a."Quantity"), a."BaseEntry", 20, a."BaseNum", 1
	from IBT1 a join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
	join OPDN d on a."BaseType"=d."ObjType" and a."BaseEntry"=d."DocEntry"
	join OITM c on a."ItemCode"=c."ItemCode"
	where d.CANCELED='N' and b."MnfSerial" is not null and b."MnfSerial"=:batch and (ifnull(:itemCode,'')='' or a."ItemCode"=:itemCode) and c."ItmsGrpCod"=113
	group by a."ItemCode", c."ItemName", a."BaseEntry", a."BaseNum", b."MnfSerial";
	
	-- Nhiều lệnh GRPO nhập cùng batch thì trả về danh sách các lệnh đó
	/* /*-- old --- Ngoc
	if exists(select 1 from #tbl group by Batch having(count(DocEntry)) > 1) then
		select * from #tbl;
		drop table #tbl;
		return;
	end if;
	*/
	
	if exists(select 1 from #tbl group by Batch having(count(DocEntry)) > 1) then
		update  a
		set a.QTY  = (select sum(QTY) from #tbl b),
			a.DOCNUM  = (select STRING_AGG(DOCNUM,',') from #tbl b) ,
			a.DocEntry =  Null
		from #tbl a
		where ID  = 1;
		
		delete from #tbl where ID  <> 1;
	end if;
	
	/* Level 2 */
	/*-- old --- Ngoc
	insert into #tbl (ParentID, ItemCode, ItemName, Batch, Qty, DocEntry, DocType, DocNum, Lvl)
	select d.ID, d.ItemCode, d.ItemName, d.Batch, sum(a."Quantity"), c."DocEntry", 202, c."DocNum", 2
	from IBT1 a join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
	join OWOR c on c."ObjType"=a."BsDocType" and c."DocEntry"=a."BsDocEntry"
	join #tbl d on d.ItemCode=a."ItemCode" and d.Batch=b."MnfSerial"
	where a."BaseType"=60
	group by d.ID, d.ItemCode, d.ItemName, d.Batch, c."DocEntry", c."DocNum";
	*/
	insert into #tbl (ParentID, ItemCode, ItemName, Batch, Qty, DocEntry, DocType, DocNum, Lvl)
	select ID, ItemCode,ItemName,Batch, sum("Receipt_Qty")  - sum("Issued_Qty"),"DocEntry", 202, "DocNum", 2
	from  
	 (
			select d.ID, d.ItemCode, d.ItemName, d.Batch,  "BaseType",
					case when a."BaseType" = 59 then a."Quantity" else 0 end  as "Receipt_Qty", 
					case when a."BaseType" = 60 then a."Quantity" else 0 end  as "Issued_Qty", 
					c."DocEntry", 202, c."DocNum", 2
			from IBT1 a join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
			join OWOR c on c."ObjType"=a."BsDocType" and c."DocEntry"=a."BsDocEntry"
			join #tbl d on d.ItemCode=a."ItemCode" and d.Batch=b."MnfSerial"
			where a."BaseType" in (59,60)
			) as Lvel2
			group by ID, ItemCode, ItemName, Batch, "DocEntry", "DocNum";
	
	
	
	/* Level 3 */
	-- Danh sách lệnh sản xuất mà các batch NVL trên tham gia
	lstPO = select distinct "BsDocEntry" "DocEntry", a."ItemCode", b."MnfSerial" from IBT1 a join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
	join #tbl c on a."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch
	where a."BaseType"=60 and a."BsDocType"=202;
	
	-- Receipt Thành phẩm
	insert into #tbl (ParentID, ItemCode, ItemName, Batch, Qty, DocEntry, DocType, DocNum, Lvl)
	select c.ID, d."ItemCode", f."ItemName", e."MnfSerial", sum(d."Quantity"), a."DocEntry", 202, a."DocNum", 3
	from OWOR a join :lstPO b on a."DocEntry"=b."DocEntry" join #tbl c on b."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch and c.DocType=202 and c.DocEntry=b."DocEntry"
	join IBT1 d on d."BaseType"=59 and d."BsDocType"=202 and d."BsDocEntry"=a."DocEntry" and d."BsDocLine"=-1
	join OBTN e on e."ItemCode"=d."ItemCode" and e."DistNumber"=d."BatchNum"
	join OITM f on f."ItemCode"=d."ItemCode"
	group by d."ItemCode", f."ItemName", a."DocEntry", e."MnfSerial", c.ID, a."DocNum"
	
	union all
	
	-- Receipt line production order có planned qty < 0 (tránh trường hợp return component)
	select c.ID, d."ItemCode", f."ItemName", e."MnfSerial", sum(d."Quantity"), a."DocEntry", 202, a1."DocNum", 3
	from WOR1 a join OWOR a1 on a."DocEntry"=a1."DocEntry"
	join :lstPO b on a."DocEntry"=b."DocEntry"
	join #tbl c on b."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch and c.DocType=202 and c.DocEntry=b."DocEntry"
	join IBT1 d on d."BaseType"=59 and d."BsDocType"=202 and d."BsDocEntry"=a."DocEntry" and d."BsDocLine"=a."LineNum"
	join OBTN e on e."ItemCode"=d."ItemCode" and e."DistNumber"=d."BatchNum"
	join OITM f on f."ItemCode"=d."ItemCode"
	where a."PlannedQty"<0
	group by d."ItemCode", f."ItemName", a."DocEntry", e."MnfSerial", c.ID, a1."DocNum";
	
	/* Level 4 */
	-- Danh sách lệnh sản xuất có tiêu hao các batch rework trên
	lstPO = select distinct "BsDocEntry" "DocEntry", a."ItemCode", b."MnfSerial" from IBT1 a join OBTN b on a."BatchNum"=b."DistNumber" and a."ItemCode"=b."ItemCode"
	join #tbl c on a."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch
	join OITM d on a."ItemCode"=d."ItemCode"
	where a."BaseType"=60 and a."BsDocType"=202 and c.Lvl = 3
		and d."ItmsGrpCod"=121; -- 121 là group Thành phẩm - rework

	insert into #tbl (ParentID, ItemCode, ItemName, Batch, Qty, DocEntry, DocType, DocNum, Lvl)
	select c.ID, d."ItemCode", f."ItemName", e."MnfSerial", sum(d."Quantity"), a."DocEntry", 202, a."DocNum", 4
	from OWOR a join :lstPO b on a."DocEntry"=b."DocEntry" join #tbl c on c.Lvl = 3 and b."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch
	join IBT1 d on d."BaseType"=59 and d."BsDocType"=202 and d."BsDocEntry"=a."DocEntry" and d."BsDocLine"=-1
	join OBTN e on e."ItemCode"=d."ItemCode" and e."DistNumber"=d."BatchNum"
	join OITM f on f."ItemCode"=d."ItemCode"
	group by d."ItemCode", f."ItemName", a."DocEntry", e."MnfSerial", c.ID, a."DocNum"
	union all
	select c.ID, d."ItemCode", f."ItemName", e."MnfSerial", sum(d."Quantity"), a."DocEntry", 202, a1."DocNum", 4
	from WOR1 a join OWOR a1 on a."DocEntry"=a1."DocEntry"
	join :lstPO b on a."DocEntry"=b."DocEntry"
	join #tbl c on c.Lvl = 3 and b."ItemCode"=c.ItemCode and b."MnfSerial"=c.Batch
	join IBT1 d on d."BaseType"=59 and d."BsDocType"=202 and d."BsDocEntry"=a."DocEntry" and d."BsDocLine"=a."LineNum"
	join OBTN e on e."ItemCode"=d."ItemCode" and e."DistNumber"=d."BatchNum"
	join OITM f on f."ItemCode"=d."ItemCode"
	where a."PlannedQty"<0
	group by d."ItemCode", f."ItemName", a."DocEntry", e."MnfSerial", c.ID, a1."DocNum";
	-- Insert them item lvel 3
	insert into #tbl ( ItemCode, ItemName, Batch, Qty,DocEntry, DocType, DocNum, Lvl)

	select ItemCode,ItemName,Batch,Qty,WOID,202,WONO,3 from #pro04 
	where  ItemCode  IN (select ItemCode from #tbl where  LVL =3 )
	 and  BATCH||ItemCode not in (select BATCH||ItemCode from #tbl where LVL =  3)
	 and Batch in (select Batch  from #tbl where LVL =  3);
	 --Update  ParentID Lvel 3
	 update a 
	 set ParentID = (select max(ParentID) from   #tbl b 
	 							where b.LVL = 3   and a.ItemCode = b.ItemCode
	 								 and a.DocNum = b.DocNum) 
	  
	 from #tbl a
	 where ifnull(ParentID, 0) = 0   and LVL = 3;
	 
	 --- Insert them item lvel 4
	 insert into #tbl ( ItemCode, ItemName, Batch, Qty,DocEntry, DocType, DocNum, Lvl)

	select ItemCode,ItemName,Batch,Qty,WOID,202,WONO,4 from #pro04 
	where  ItemCode  IN (select ItemCode from #tbl where  LVL =4 )
	 and  BATCH||ItemCode not in (select BATCH||ItemCode from #tbl where LVL =  4)
	 and Batch in (select Batch  from #tbl where LVL =  4);
	 -- Update  ParentID Lvel 4
	 update a 
	 set ParentID = (select max(ParentID) from   #tbl b 
	 							where b.LVL = 4   and a.ItemCode = b.ItemCode
	 								 and a.DocNum = b.DocNum)
	 from #tbl a
	 where ifnull(ParentID, 0) = 0   and LVL = 4;
--
	update a
	set a.QTY  = b.QTY
	from #tbl a
	left join  #pro04 b on a.DocNum  = b.WONO and  a.ITEMCODE  = b.ITEMCODE and a.BATCH  = b.BATCH
	where  LVL in (3,4);
 ---
	update #tbl
	set QTY = QTY * -1
	where QTY <0;
 


	select * from #tbl order by ifnull(PARENTID,0),ItemCode,Lvl;
	--
	drop table #tbl;
	drop table #pro04;
	
end

