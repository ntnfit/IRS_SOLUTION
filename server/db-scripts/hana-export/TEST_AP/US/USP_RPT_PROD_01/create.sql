CREATE procedure USP_RPT_PROD_01 (
	in groupID			int,
	in FGCode			nvarchar(50),
	in branch			int
)
as
begin
	
	-- ĐỊNH MỨC SẢN XUẤT----------------------------------------------------------------------------------------------
	----------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tbl (
		ID				int not null primary key generated by default as IDENTITY,
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		Warehouse		nvarchar(20),
		Qty				numeric(21,6),
		LevelNo			int,
		FullCode		nvarchar(1000),
		FatherFullCode	nvarchar(1000),
		ParrentID		int,
		Note			nvarchar(100)
	);
	-------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblWH (
		WHCode			nvarchar(20),
		WHName			nvarchar(100),
		WHAccount		nvarchar(20)
	);
	insert into #tblWH (WHCode,WHName,WHAccount) select "WhsCode","WhsName","BalInvntAc" from "OWHS" where (branch in (-1,0) or "BPLid"=branch);
	------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblITEM (
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		UoM				nvarchar(50),
		InventoryAcct	nvarchar(20),
		GLMethod		char(1),
		GrpID			int,
		GrpName			nvarchar(100)
	);
	insert into #tblITEM (ItemCode,ItemName,UoM,GrpID,GrpName,GLMethod,InventoryAcct) 
	select a."ItemCode",a."ItemName",a."InvntryUom",b."ItmsGrpCod",b."ItmsGrpNam",a."GLMethod",case when a."GLMethod"='C' then b."BalInvntAc" end
	from "OITM" a, "OITB" b 
	where a."ItmsGrpCod"=b."ItmsGrpCod";
	-- BOM ----------------------------------------------------------------------------------------------------------------
	create local temporary table #tblBOM (
		FCode		nvarchar(50),
		SCode		nvarchar(50),
		WH			nvarchar(20),
		Qty			numeric(21,6)
	);
	insert into #tblBOM (FCode,SCode,WH,Qty)
	select a."Code",b."Code",b."Warehouse",sum(b."Quantity"/a."Qauntity") as Quantity from "OITT" a, "ITT1" b where a."Code"=b."Father" group by a."Code",b."Code",b."Warehouse";
	-- FG
	create local temporary table #tblFG (
		FCode		nvarchar(50),
		WH			nvarchar(20)
	);
	insert into #tblFG (FCode,WH) 
	select FCode,WH 
	from #tblBOM a, "OITM" b
	where a.FCode not in (select x."Code" from "ITT1" x) 
	and a.FCode=b."ItemCode" 
	and (b."ItemCode"=FGCode or FGCode='')
	and (b."ItmsGrpCod"=groupID or groupID=0)
	group by FCode,WH;
	--RAW DATA ---------------------------------------------------------------------------------------------------------------
	create local temporary table #tblDATA (
		ID				int not null primary key generated by default as IDENTITY,
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		Warehouse		nvarchar(20),
		Qty				numeric(21,6),
		FullCode		nvarchar(1000),
		FatherFullCode	nvarchar(1000),
		ParrentID		int,
		Note			nvarchar(100)
	);
	-- REPORT ----------------------------------------------------------------------------------------------------------------
	
	-- Level 1
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 1,FCode,1,WH,'',FCode from #tblFG T1;
	-- Level 2
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 2,T2.SCode,T2.Qty,T2.WH,T2.FCode,CONCAT(T2.FCode,T2.SCode) from #tblFG T1, #tblBOM T2 where T1.FCode=T2.FCode;
	-- Level 3
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 3,T3.SCode,T3.Qty,T3.WH,CONCAT(T2.FCode,T2.SCode),CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3 where T1.FCode=T2.FCode and T2.SCode=T3.FCode;
	-- Level 4
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 4,T4.SCode,T4.Qty,T4.WH,CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode;
	-- Level 5
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 5,T5.SCode,T5.Qty,T5.WH,CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode;
	-- Level 6
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 6,T6.SCode,T6.Qty,T6.WH,CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5, #tblBOM T6 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode and T5.SCode=T6.FCode;
	-- Level 7
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 7,T7.SCode,T7.Qty,T7.WH,CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5, #tblBOM T6, #tblBOM T7 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode and T5.SCode=T6.FCode and T6.SCode=T7.FCode;
	-- Level 8
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 8,T8.SCode,T8.Qty,T8.WH,CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),T8.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5, #tblBOM T6, #tblBOM T7, #tblBOM T8 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode and T5.SCode=T6.FCode and T6.SCode=T7.FCode and T7.SCode=T8.FCode;
	-- Level 9
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 9,T9.SCode,T9.Qty,T9.WH,CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),T8.SCode),CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),T8.SCode),T9.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5, #tblBOM T6, #tblBOM T7, #tblBOM T8, #tblBOM T9 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode and T5.SCode=T6.FCode and T6.SCode=T7.FCode and T7.SCode=T8.FCode and T8.SCode=T9.FCode;
	-- Level 10
	insert into #tbl (LevelNo,ItemCode,Qty,Warehouse,FatherFullCode,FullCode) 
	select 10,T10.SCode,T10.Qty,T10.WH,CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),T8.SCode),T9.SCode),CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(T2.FCode,T2.SCode),T3.SCode),T4.SCode),T5.SCode),T6.SCode),T7.SCode),T8.SCode),T9.SCode),T10.SCode) from #tblFG T1, #tblBOM T2, #tblBOM T3, #tblBOM T4, #tblBOM T5, #tblBOM T6, #tblBOM T7, #tblBOM T8, #tblBOM T9, #tblBOM T10 where T1.FCode=T2.FCode and T2.SCode=T3.FCode and T3.SCode=T4.FCode and T4.SCode=T5.FCode and T5.SCode=T6.FCode and T6.SCode=T7.FCode and T7.SCode=T8.FCode and T8.SCode=T9.FCode and T9.SCode=T10.FCode;

	-- Parrent Key
	update #tbl set ParrentID = (select (x.ID) from #tbl x where x.FullCode=#tbl.FatherFullCode);
	
	update #tbl set ItemName = (select x.ItemName from #tblITEM x where x.ItemCode=#tbl.ItemCode);
	update #tbl set ItemUoM = (select x.UoM from #tblITEM x where x.ItemCode=#tbl.ItemCode);
	update #tbl set GrpCode = (select x.GrpID from #tblITEM x where x.ItemCode=#tbl.ItemCode);
	update #tbl set GrpName = (select x.GrpName from #tblITEM x where x.ItemCode=#tbl.ItemCode);

	select * from #tbl a;

	drop table #tbl;
	drop table #tblFG;
	drop table #tblWH;
	drop table #tblBOM;
	drop table #tblITEM;
	drop table #tblDATA;
end

