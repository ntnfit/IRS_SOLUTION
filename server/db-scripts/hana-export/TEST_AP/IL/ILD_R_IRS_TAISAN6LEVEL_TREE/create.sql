CREATE procedure ILD_R_IRS_TaiSan6Level_Tree
(
	in TaiSanCode nvarchar(250)
)
as
begin
	create local temporary table #tbl (
		ID 				int not null primary key generated by default as IDENTITY ,
		
		PIID			int,
		Code nvarchar(250),
		Name nvarchar(250),
		Quantity int,
		UOM nvarchar(20),
		Level	nvarchar(2),
		Qty		numeric(21,2)
		
		
				
	);
	
	-- danh sach Nha May Cap 1
	create local temporary table #listNhaMay1(
		ID 				int not null primary key generated by default as IDENTITY ,
		U_Level1	nvarchar(50),
		FixAssetCode nvarchar(250),
		FixAssetName nvarchar(250),
		Floc nvarchar(250), --Level5
		ItemCode nvarchar(50), --Level6
		ItemName nvarchar(250), --Level6
		Quantity int,
		UOM nvarchar(20)	
	);
	insert into #listNhaMay1(U_Level1,FixAssetCode,FixAssetName)
	select "U_Level1","ItemCode" as "FixAssetCode", "ItemName" as "FixAssetName"
	from OITM a 
	where   a."ItemType"  =  'F' and ifnull("U_Level1",'') <> ''  ;
	
	-- danh sach quy trình
	create local temporary table #listNhaMay2(
		ID 				int not null primary key generated by default as IDENTITY ,
		U_Level1 nvarchar(50),
		U_Level2	nvarchar(50),
		FixAssetCode nvarchar(50),
		FixAssetName nvarchar(250),
		Floc nvarchar(250), --Level5
		ItemCode nvarchar(250), --Level6
		ItemName nvarchar(100), --Level6
		Quantity int,
		UOM nvarchar(20)	
	);
	insert into #listNhaMay2(U_Level1,U_Level2,FixAssetCode,FixAssetName)
	select  distinct "U_Level1","U_Level2","ItemCode" as "FixAssetCode", "ItemName" as "FixAssetName"
	from OITM a 
	where   a."ItemType"  =  'F' and ifnull("U_Level1",'') <> '' and ifnull("U_Level2",'') <> '';
	
	-- danh sach hệ thống
	create local temporary table #listNhaMay3(
		ID 				int not null primary key generated by default as IDENTITY ,
		U_Level1 nvarchar(50),
		U_Level2	nvarchar(50),
		U_Level3	nvarchar(50),
		FixAssetCode nvarchar(50),
		FixAssetName nvarchar(250),
		Floc nvarchar(250), --Level5
		ItemCode nvarchar(50), --Level6
		ItemName nvarchar(250), --Level6
		Quantity int,
		UOM nvarchar(20)	
	);
	insert into #listNhaMay3(U_Level1,U_Level2,U_Level3,FixAssetCode,FixAssetName)
	select distinct "U_Level1","U_Level2","U_Level3","ItemCode" as "FixAssetCode", "ItemName" as "FixAssetName"
	from OITM a 
	where   a."ItemType"  =  'F' and ifnull(a."U_IsAdditionFee",0) = 0;
	
	
	-- danh sach tai san Cap 5
	create local temporary table #bom
	(
		ID 				int not null primary key generated by default as IDENTITY ,
		U_Level3	nvarchar(50),
		FixAssetCode nvarchar(250), 
		FixAssetName nvarchar(250),
		Floc nvarchar(250), 
		ItemCode nvarchar(50), 
		ItemName nvarchar(250), 
		Quantity int,
		UOM nvarchar(20)
		
	);
	insert into #bom (FixAssetCode, FixAssetName, Floc, ItemCode, ItemName, Quantity, UOM)
	select distinct a."U_ItemCodeF" as "FixAssetCode", 
		   a."U_ItemNameF" as "FixAssetName",
		   b."U_Floc",
	   	   b."U_ItemCode",
	   	   b."U_ItemName",
	   	   b."U_Quantity",
	       b."U_UOM"
	from  "@BOMAINTENANCE_H" a
	inner join "@BOMAINTENANCE_L" b on a."DocEntry"  = b."DocEntry"
	where 1 = 1 
	;
	
	
	-- danh sach tai san Cap 4
	create local temporary table #taisan
	(
		ID 			int not null primary key generated by default as IDENTITY ,
		U_Level3	nvarchar(250),
		FixAssetCode nvarchar(250), 
		FixAssetName nvarchar(250)
		
	);
	insert into #taisan (U_Level3,FixAssetCode,FixAssetName)
	select distinct "U_Level3","ItemCode" as "FixAssetCode", "ItemName" as "FixAssetName"
	from OITM a 
		inner join  #bom b on a."ItemCode"  =  b.FixAssetCode 
	where   a."ItemType"  =  'F' and ifnull(a."U_Level3",'') <> '' and (
				 ifnull(:TaiSanCode, '') = '' 
				 or cast (a."ItemCode" as nvarchar) in (select "DATA" from split(:TaiSanCode,','))
			)
	;
	
	-- danh sach tai san Cap 6
	create local temporary table #ItemCode
	(
		ID 				int not null primary key generated by default as IDENTITY ,
		U_Level3	nvarchar(250),
		FixAssetCode nvarchar(250),
		FixAssetName nvarchar(250),
		Floc nvarchar(250), --Level5
		ItemCode nvarchar(250), --Level6
		ItemName nvarchar(250), --Level6
		Quantity int,
		UOM nvarchar(20)
		
	);
	insert into #ItemCode (FixAssetCode, FixAssetName, Floc, ItemCode, ItemName, Quantity, UOM)
	select distinct a."U_ItemCodeF" as "FixAssetCode", 
		   a."U_ItemNameF" as "FixAssetName",
		   b."U_Floc",
	   	   b."U_ItemCode",
	   	   b."U_ItemName",
	   	   b."U_Quantity",
	       b."U_UOM"
	from  "@BOMAINTENANCE_H" a
	inner join "@BOMAINTENANCE_L" b on a."DocEntry"  = b."DocEntry"
	where 1 = 1 
	;
	
	
	
	
	
	
	
	-- cap nhat bang chinh
	-- Level 1
	insert into #tbl (PIID,Code,Name,Level) 
	select distinct  null,U_Level1,U_Level1,1
	from #listNhaMay1;
	
	
	-- Level 2
	insert into #tbl (PIID,Code,Name,Level) 
	select  distinct b.ID 
	,a.U_Level2,a.U_Level2,2
	from #listNhaMay2 a
		inner join #tbl b on a.U_Level1 = b.Code;
	
	-- Level 3
	insert into #tbl (PIID,Code,Name,Level) 
	   select distinct b.ID 
	,a.U_Level3,a.U_Level3,3
	from #listNhaMay3 a
		inner join #tbl b on a.U_Level2 = b.Code;  
	
	 
	
	-- Level 4
	insert into #tbl (PIID,Code,Name,Level) 
	select distinct  b.ID 
	,a.FixAssetCode,a.FixAssetName,4
	from #taisan a
		inner join #tbl b on a.U_Level3 = b.Code;
	
	 
	-- Level 5
	insert into #tbl (PIID,Code,Name,Level) 
	select distinct b.ID 
	,a.Floc,a.Floc,5
	from #bom a
		inner join #tbl b on a.FixAssetCode = b.Code ; 
	
	
	
	-- Level 6
	insert into #tbl (PIID,Code,Name,Qty,UOM,Level) 
	select  
	distinct c.ID,a.ItemCode,a.ItemName,sum(a.Quantity),a.UOM,6
	from #ItemCode a
		inner join #tbl b on a.FixAssetCode = b.Code  
		inner join #tbl c on a.Floc = c.Code  
	group by c.ID,a.ItemCode,a.ItemName,a.UOM;
	
	

	select  * from #tbl;
	
	drop table #tbl;
	drop table #listNhaMay1;
	drop table #listNhaMay2;
	drop table #listNhaMay3;
	drop table #bom;
	drop table #taisan;
	drop table #ItemCode;
	
end;
