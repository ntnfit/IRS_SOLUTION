CREATE procedure ILD_WH09_TB(
	in fdate			timestamp,
	in tdate			timestamp,
	in groupID			int,
	in warehouse		nvarchar(20),
	in account			nvarchar(20),
	in itemcode			nvarchar(5000),
	in cancel			int,
	out TB table (
		ID				int /*not null primary key generated by default as IDENTITY*/,
		Pos				int,
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		DocType			nvarchar(20),
		AppObj			nvarchar(10),
		DocNote			nvarchar(50),
		DocID			int,
		DocDate			timestamp,
		Comments		nvarchar(300),
		Warehouse		nvarchar(20), 
		INQty			numeric(21,6),
		INAmt			numeric(21,6),
		
		OUQty			numeric(21,6),
		OUAmt			numeric(21,6),
		BalQty			numeric(21,6),
		BalAmt			numeric(21,6),
		Note			nvarchar(100),
		DocTime 		varchar(10),
		DocNum			nvarchar(50),
		InQtyPre		numeric(21,6),
		OuQtyPre		numeric(21,6),
		
		INPrice			numeric(21,6),
		OUPrice			numeric(21,6),
		BalPrice		numeric(21,6)
		

		-- 
		,SoToKhai		nvarchar(50)
		,Invoice		nvarchar(50)
		,InvoiceDate	timestamp
		,BPCode			nvarchar(50)
		,BPName			nvarchar(254)
		,PO				nvarchar(50)
		,DebitAcc		nvarchar(50)
		,CreditAcc		nvarchar(50)
		,MaMD			nvarchar(254)
		,TenMD			nvarchar(254)
		,Diengiai		nvarchar(254)
		-- Thong tin lenh san xuat
		,WOID int
		,WONum varchar(30)
		,WOType varchar(15)
	)
)
as
begin
	-- CHI TIẾT NHẬP XUẤT TỒN----------------------------------------------------------------------------------------------
	create local temporary table #tbl as (
		select * from :TB

	);
	-------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblWH (
		WHCode			nvarchar(20),
		WHName			nvarchar(100),
		WHAccount		nvarchar(20)
	);
	insert into #tblWH (WHCode,WHName,WHAccount) select "WhsCode","WhsName","BalInvntAc" from "OWHS" 
	where 
		--(branch in (-1,0) or "BPLid"=branch) and 
		(warehouse='' or "WhsCode"=warehouse);
	------------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblITEM (
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		UoM				nvarchar(50),
		InventoryAcct	nvarchar(20),
		GLMethod		char(1),
		GrpID			int,
		GrpName			nvarchar(100)
	);
	insert into #tblITEM (ItemCode,ItemName,UoM,GrpID,GrpName,GLMethod,InventoryAcct) 
	select a."ItemCode",a."ItemName",a."InvntryUom",b."ItmsGrpCod",b."ItmsGrpNam",a."GLMethod",case when a."GLMethod"='C' then b."BalInvntAc" end
	from "OITM" a, "OITB" b 
	where a."ItmsGrpCod"=b."ItmsGrpCod" and a."InvntItem"='Y'
	and (b."ItmsGrpCod"=groupID or groupID=0)
	and
			(
			IFNULL(:itemcode, '') = '' OR cast ("ItemCode" as nvarchar) IN (SELECT "DATA" FROM "SPLIT"(:itemcode, ','))
			--ifnull((select STRING_AGG( Code) from :itemcode), '') = '' OR cast (a."ItemCode" as nvarchar) IN (select Code from :itemcode)
			) 
	;
	--------------------------------------------------------------------------------------------------------------------------
	--RAW DATA ---------------------------------------------------------------------------------------------------------------
	create local temporary table #tblDATA (
		GrpCode			int,
		GrpName			nvarchar(100),
		ItemCode		nvarchar(50),
		ItemName		nvarchar(100),
		ItemUoM			nvarchar(50),
		TransNum		int,
		DocType			nvarchar(20),
		AppObj			nvarchar(10),
		DocID			int,
		DocDate			timestamp,
		Comments		nvarchar(300),
		Warehouse		nvarchar(20), 
		InQty			numeric(21,6),
		InQtyPre		numeric(21,6),
		OuQty			numeric(21,6),
		OuQtyPre		numeric(21,6),
		Amount			numeric(21,6),
		CardCode		nvarchar(50),
		DebitAcc		nvarchar(50),
		CreditAcc		nvarchar(50)
	);
	insert into #tblDATA (GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse,InQty,OuQty,Amount,DocDate,DocType,AppObj,DocID,Comments,TransNum,
	InQtyPre,OuQtyPre,DebitAcc,CreditAcc
	)
	select c.GrpID,c.GrpName,c.ItemCode,c.ItemName,c.UoM,b.WHCode
	,(
		 CASE when a."TransType" in ('14','18','20','69','162','21','60','59') then (IFNULL(a."InQty",0)-IFNULL(a."OutQty",0)) -- thêm 21 vào vì yêu cầu 21 là âm bên nhập, thêm 60 vì yêu cầu ghi âm bên cột nhập
						else 
							CASE when a."TransType" not in ('13','15','19','16') then a."InQty" end -- bỏ 21 ra vì yêu cầu 21 là âm bên nhập, 59 thì ghi âm qua cột xuất
						end
	
	)
	,(
		 CASE when a."TransType" in ('13','15','19','16') then -IFNULL(a."InQty",0)+IFNULL(a."OutQty",0) -- bỏ 21 ra vì yêu cầu 21 là âm bên nhập,59 thì ghi âm qua cột xuất
						else 
							CASE when a."TransType" not in ('14','18','20','69','162','21','60','59') then a."OutQty" end -- thêm 21 vào vì yêu cầu 21 là âm bên nhập, thêm 60 vì yêu cầu ghi âm bên cột nhập
						end
	)
	,a."TransValue",a."DocDate",a."TransType",a."ApplObj",a."CreatedBy",a."Comments",a."TransNum"
	,IFNULL(a."InQty",0)-IFNULL(a."OutQty",0)
	,-IFNULL(a."InQty",0)+IFNULL(a."OutQty",0)
	,case when a."TransValue" > 0 then a."InvntAct" when a."TransValue" < 0 then (case when a."TrnsfrAct" <> '' then a."TrnsfrAct" when a."CostAct" <> '' then a."CostAct" when a."WipAct" <> '' then a."WipAct" when a."DOffDecAcc" <> '' then a."DOffDecAcc" when a."IOffIncAcc" <> '' then a."IOffIncAcc" end) end
	,case when a."TransValue" < 0 then a."InvntAct" when a."TransValue" > 0 then (case when a."TrnsfrAct" <> '' then a."TrnsfrAct" when a."CostAct" <> '' then a."CostAct" when a."WipAct" <> '' then a."WipAct" when a."DOffDecAcc" <> '' then a."DOffDecAcc" when a."IOffIncAcc" <> '' then a."IOffIncAcc" end) end
	from "OINM" a, #tblWH b, #tblITEM c--, APZ_ODOC d
	where a."DocDate"<=tdate and a."Warehouse"=b.WHCode and a."ItemCode"=c.ItemCode  --and a."TransType" = d."ObjType"
	--and a."CreatedBy" = d."DocEntry" 
	--and ( :cancel = 2 or  ifnull(d."CANCELED", 'N') = 'N')
	--and (a."InvntAct" like '155%' or a."InvntAct" like '1541%')
	and c.GrpID in (120,127) --Thành phẩm, 127: Thành phẩm-Oil Coffee
	
	and (account='' 
		or (ifnull(a."InvntAct",'')<>'' and a."InvntAct"=account) 
		or (ifnull(a."InvntAct",'')='' and c.GLMethod='C' and c.InventoryAcct=account)
		or (ifnull(a."InvntAct",'')='' and c.GLMethod='W' and b.WHAccount=account)
	);
	
	-- update CardCode ObjType = 20
	update x set CardCode = (select "CardCode" from OPDN where "ObjType" = x.DocType and "DocEntry" = x.DocID)  from #tblDATA x where  DocType = 20;

	

	create local temporary table #tblBALANCE (
		ItemCode		nvarchar(50),
		Qty				numeric(21,6),
		Amount			numeric(21,6)
	);
	-- REPORT ----------------------------------------------------------------------------------------------------------------
	-- Số dư đầu kỳ -------------------------
	
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,BalQty,BalAmt,Comments)
	
	select 1,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,
		sum(InQtyPre),sum(Amount),
		'Số dư đầu kỳ'
	from #tblDATA
	where DocDate<fdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;

	insert into #tblBALANCE (ItemCode,Qty,Amount) select ItemCode,BalQty,BalAmt from #tbl;	
	-- Chi tiết phát sinh trong kỳ
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse,InQty,InAmt,OuQty,OuAmt,Comments,DocType,AppObj,DocID,DocDate,BalQty,BalAmt,InQtyPre,OuQtyPre,BPCode,DebitAcc,CreditAcc)
	select 2,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,Warehouse
	,InQty
	,case when Amount>0 then Amount else 0 end
	,OuQty
	,case when Amount>0 then 0 else -Amount end
	,Comments,DocType,AppObj,DocID,DocDate,
		ifnull(sum(InQtyPre) OVER (Partition by ItemCode order by DocDate,TransNum),0) + ifnull((select x.Qty from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		ifnull(sum(Amount) OVER (Partition by ItemCode order by DocDate,TransNum),0) + ifnull((select x.Amount from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0)
		,InQtyPre,OuQtyPre,CardCode,DebitAcc,CreditAcc
	from #tblDATA
	where DocDate between fdate and tdate
	order by ItemCode,DocDate,TransNum
	;
	update x set InAmt = -OuAmt from #tbl x where ifnull(OuQty,0) = 0 and ifnull(InQty,0) < 0;
	update x set OuAmt = -InAmt from #tbl x where ifnull(InQty,0) = 0 and ifnull(OuQty,0) < 0;
	
	/*
	-- update ObjType = 21 thi am ben cot nhap con lai gia tri ben out = 0 (xóa đi cột có InQty <> 0 nhưng vẫn có giá trị cột OuAmt)
	update x set OUAmt = null from #tbl x where InQty < 0 and DocType = 21;
	*/
	
	-- update ObjType = 60 thì âm bên cột nhập còn lại giá trị bên OUT  = 0 (xóa đi cột có InQty <>  0 nhưng vẫn có giá trị cột OuAmt)
	update x set OUAmt = null from #tbl x where InQty < 0 and DocType = 60;

	-- update ObjType = 59 thi InAmt = 0 (xóa đi cột có OutQty <> 0nhưng vẫn có giá trị cột InQty)
	update x set InAmt = null from #tbl x where OUQty < 0 and DocType = 59;
	
	-- update ObjType = 16 thi InAmt = 0 (xóa đi cột có OutQty <> 0nhưng vẫn có giá trị cột InQty)
	update x set InAmt = null from #tbl x where OUQty < 0 and DocType = 16;
	/*
	-- update các cột OUAmt k có số lượng nhưng có giá trị
	update x set OUAmt = null from #tbl x where InQty < 0 and ifnull(OUQty,0) = 0  and Pos = 2;
	
	-- update các cột InAmt k có số lượng nhưng có giá trị
	update x set INAmt = null from #tbl x where OUQty <> 0 and ifnull(InQty,0) = 0  and Pos = 2;
	*/
	
	/*
	
	-- không xóa đoạn này
	-- update cac Doctype = 60 duong ben cot nhap va co ApplObj = -1
	update x set InQty = -InQty from #tbl x where InQty < 0 and AppObj = -1 and DocType in (60);
	update x set InAmt = -InAmt from #tbl x where InAmt < 0 and AppObj = -1 and DocType in (60);
	update x set InQty = null from #tbl x where InQty < 0 and AppObj = -1 and DocType in (60);
	update x set InAmt = null from #tbl x where InAmt < 0 and AppObj = -1 and DocType in (60);
	*/
	-- update cac Doctype = 60 và co ApplObj = -1 tạm thời chuyển lại về dương bên cột xuất
	update x set OuQty = -InQty from #tbl x where InQty < 0 and AppObj = -1 and DocType in (60);
	update x set OuAmt = -InAmt from #tbl x where InAmt < 0 and AppObj = -1 and DocType in (60);
	update x set InQty = null from #tbl x where InQty < 0 and AppObj = -1 and DocType in (60);
	update x set InAmt = null from #tbl x where InAmt < 0 and AppObj = -1 and DocType in (60);
	
	
	-- Tổng phát sinh trong kỳ -------------------------
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,InQty,InAmt,OuQty,OuAmt,Comments,BalQty,BalAmt,InQtyPre,OuQtyPre)
	select 3,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,sum(InQty),sum(case when Amount>0 then Amount else 0 end),sum(OuQty),sum(case when Amount>0 then 0 else -Amount end),'Tổng phát sinh trong kỳ',
		ifnull(sum(InQtyPre),0) + ifnull((select x.Qty from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		ifnull(sum(Amount),0) + ifnull((select x.Amount from #tblBALANCE x where x.ItemCode=#tblDATA.ItemCode),0),
		sum(InQtyPre),sum(OuQtyPre)
	from #tblDATA
	where DocDate between fdate and tdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;
	
	
	-- Số dư cuối kỳ -------------------------
	insert into #tbl (Pos,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,BalQty,BalAmt,Comments)
	select 4,GrpCode,GrpName,ItemCode,ItemName,ItemUoM,
		sum(InQtyPre),sum(Amount),'Số dư cuối kỳ'
	from #tblDATA
	where DocDate<=tdate
	group by GrpCode,GrpName,ItemCode,ItemName,ItemUoM;
	
	Update a
	set DocTime = (case     when LENGTH(b."DocTime")  = 1 then  '00:0'|| b."DocTime"
							 when LENGTH(b."DocTime")  = 2 then  '00:'|| b."DocTime"				
							 when LENGTH(b."DocTime")  = 3 then  '0'||left(b."DocTime",1) || ':' || right(b."DocTime",2) 
		 					 when LENGTH(b."DocTime")  = 4 then   left(b."DocTime",2) || ':' || right(b."DocTime",2)  
	 			else  '' end  ),
	 	DocNum = b."BASE_REF"
	 			
	from #tbl a
	left join  OINM b on a.DOCID =b."CreatedBy" and a.DOCTYPE  = b."TransType";
	
	
	
	-- update lại gias tri tổng phát sinh (do custom nên lọt trương hợp số lượng OutQty < 0 nhưng giá trị = 0 và giá trị nhập > 0) = > update lại GT nhâp null và GT xuất = -GT nhập
	update x set OuAmt = - InAmt from #tbl x where InAmt > 0 and (select sum(OuQty) from #tbl where ItemCode = x.ItemCode) < 0 and Pos = 3;
		-- ngược lại =  null
	update x set InAmt = null from #tbl x where  ifnull((select sum(InQty) from #tbl where ItemCode = x.ItemCode),0) >= 0 and Pos = 3;
	/*
	-- update lại tổng phát sinh
	update x set InAmt = (select sum(InAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	update x set InQty = (select sum(InQty) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	update x set OuAmt = (select sum(OuAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	--update x set BalAmt = (select sum(BalAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	*/
	-- update lại tổng phát sinh
	update x set InAmt = (select sum(InAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	update x set OuAmt = (select sum(OuAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	
	update x set InQty = (select sum(InQty) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	update x set OuQty = (select sum(OuQty) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;
	--update x set BalAmt = (select sum(BalAmt) from #tbl where Pos = 2 and ItemCode = x.ItemCode) from #tbl x where Pos = 3;


	update #tbl set DocNote = 'A/R Invoice' where DocType='13';
	update #tbl set DocNote = 'A/R Credit Memo' where DocType='14';
	update #tbl set DocNote = 'Delivery' where DocType='15';
	update #tbl set DocNote = 'Return' where DocType='16';
	update #tbl set DocNote = 'A/P Invoice' where DocType='18';
	update #tbl set DocNote = 'A/P Credit Memo' where DocType='19';
	update #tbl set DocNote = 'Goods Receipt PO' where DocType='20';
	update #tbl set DocNote = 'Goods Return' where DocType='21';
	update #tbl set DocNote = 'Goods Receipt' where DocType='59' and AppObj='-1';
	update #tbl set DocNote = 'Receipt from Production' where DocType='59' and AppObj='202';
	update #tbl set DocNote = 'Goods Issue' where DocType='60' and AppObj='-1';
	update #tbl set DocNote = 'Issue for Production' where DocType='60' and AppObj='202';
	update #tbl set DocNote = 'Inventory Transfer' where DocType='67';
	update #tbl set DocNote = 'Landed Costs' where DocType='69';
	update #tbl set DocNote = 'Revaluation' where DocType='162';
	------------
	
	--
	update x set SoToKhai = (select "U_SoToKhai" from OPDN where "ObjType" = x.DocType and "DocEntry" = x.DocID) from #tbl x where DocType = 20;
	update x set Invoice = (select "U_InvNo" from OPDN where "ObjType" = x.DocType and "DocEntry" = x.DocID)  from #tbl x where  DocType = 20;
	update x set InvoiceDate = (select "U_InvDate" from OPDN where "ObjType" = x.DocType and "DocEntry" = x.DocID)  from #tbl x where  DocType = 20;
	-- chỉ lấy CardCode trên GRPO , CardCode trên OINM lấy khác 
	update x set BPName = (select "CardName" from OCRD where "CardCode" = x.BPCode)  from #tbl x where  DocType = 20;
	
	update x set PO = (select "U_InvNo" from OPDN where "ObjType" = x.DocType and "DocEntry" = x.DocID)  from #tbl x where  DocType = 20;

	-- 
	update x set INPrice = INAmt/ INQty from #tbl x where INQty <> 0;
	update x set OUPrice = OUAmt/ OUQty from #tbl x where OUQty <> 0;
	update x set BalPrice = BalAmt/ BalQty from #tbl x where BalQty <> 0;
	
	--
	update x set MaMD = (select "U_TransType" from OIGE where "DocEntry" = x.DocID) from # tbl x where DocType = 60;
	update x set MaMD = (select "U_TransType" from OIGN where "DocEntry" = x.DocID) from # tbl x where DocType = 59;
	update x set TenMD = (select "Name" from "@TRANS_TYPE" where "Code" = x.MaMD) from # tbl x where DocType in (59,60);
	update x set TenMD = DocNote from #tbl x where DocType not in (59,60);

 	update x set MaMD = DocType from #tbl x where DocType not in (59,60);
	update x set TenMD = DocNote from #tbl x where MaMD is null;
	
	--nếu DocNote = Good Issued và DocID = IssuedID thì TenMD = 'Issued For OutSourcing'
	update x set TenMD = 'Issued for OutSourcing' from #tbl x where exists (select 1 from "@TBL_OUTS_DOCNUM" where "U_issueID" = x.DocID) and x.DocNote = 'Goods Issue';
	
	--nếu DocNote = Good Receipt và DocID = ReceiptID thì TenMD = 'Receipt From OutSourcing'
	update x set TenMD = 'Receipt from OutSourcing' from #tbl x where exists (select 1 from "@TBL_OUTS_DOCNUM" where "U_receiptID" = x.DocID) and x.DocNote = 'Goods Receipt';
	--Phiếu Goods Receipts số 1704230005, sửa "Mục đích xuất nhập kho" từ "Goods Receipt" thành "Receipt from Outsourcing"
	update a
	set TenMD  = 'Receipt from Outsourcing'
	from  #tbl a 
	where DocNum  = '1704230005' and DocType =  59;
	--Phiếu Goods Issue số 1603230016, sửa "Mục đích xuất nhập kho" từ "Goods Issue" thành "Issue for Outsourcing"
	update a
	set TenMD  = 'Issue for Outsourcing'
	from  #tbl a 
	where DocNum  = '1603230016' and DocType =  60;
	--update thong tin lenh san xuat cho phieu nhap va xuat 
	update  a
	set a.WOID =  b."WOID",
		a.WOType  = b."WOType",
		a.WONum	 = b."WONum"
	from #tbl a
	inner join  (select bb."CreatedBy" as "DocEntry",  bb."AppObjAbs" as "WOID", bb."TransType",
				        c."Type" as "WOType",
				        c."DocNum" as "WONum"
					   
					from oinm bb
					inner join OWOR c on bb."AppObjAbs"  = c."DocEntry"
				    WHERE "DocDate" Between fdate and tdate
				    	   and "ApplObj"  = 202 AND "TransType" in (59,60)) b on b."DocEntry"  = a.DocID and b."TransType" = a.DocType;


    --

	update a
	set TenMD  = 'Issue for Disassembly'
	from #tbl a
	where DocNote  = 'Issue for Production' and WOType = 'D';
   

	-- update tai khoan
	--update x set DebitAcc  = (select "Account" from JDT1 where "TransType" = x.DocType and "CreatedBy" = x.DocID and "Debit" > 0 and ( "Account" like '152%' or "ContraAct" like '152%')) from #tbl x;
	--update x set CreditAcc  = (select "Account" from JDT1 where "TransType" = x.DocType and "CreatedBy" = x.DocID and "Credit" > 0 and ( "Account" like '152%' or "ContraAct" like '152%')) from #tbl x;

	update x set DebitAcc = CreditAcc from #tbl x where DocType = 67 and CreditAcc like '155%';
	update x set CreditAcc = DebitAcc from #tbl x where DocType = 67 and DebitAcc like '155%';


	TB = 
	select *
	/*
	DocDate 		"Ngày"
	,DocID			"DocID"
	,DocNum			"Số chứng từ nhập / xuất kho"
	,SoToKhai		"Số tờ khai"
	,Invoice		"Số Invoice"
	,InvoiceDate	"Ngày Invoice"
	,BPCode			"Mã khách hàng"
	,BPName			"Tên khách hàng"	
	,PO				"Đơn hàng"
	,ItemCode		"Mã sản sản phẩm"
	,ItemName		"Tên sản phẩm"
	,DocType		
	,DocNote		"Doc Note"
	,ItemUoM		"ĐVT"
	,MaMD			"Mã mục đích xuất nhập kho"
	,TenMD			"Mục đích xuất nhập kho"
	,INQty			"Số lượng Nhập"
	,INPrice		"Đơn giá nhập"	
	,INAmt			"Trị giá NT Nhập"
	,OUQty			"Số lượng Xuất"
	,OUPrice		"Đơn giá xuất"	
	,OUAmt			"Trị giá NT Xuất"
	
	,BalQty			"Số lượng Tồn cuối"
	,BalPrice		"Đơn giá Tồn cuối"
	,BalAmt			"Trị giá Tồn cuối"
