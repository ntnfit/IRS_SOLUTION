

CREATE PROCEDURE APZ_Commons_Exists_Transactions(in cnt integer default 0)
AS
BEGIN 
	SELECT COUNT(*) INTO cnt FROM (SELECT COUNT(1) AS "Cnt" FROM OILM 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OOAT 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OOPR 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OWOR 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OCLG 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM ODRF 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OITM 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OSCL 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OSPP 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OQUT 
	UNION 
	SELECT COUNT(1) AS "Cnt" FROM OPQT) AS X;
IF (:cnt > 0) THEN 
	SELECT 'Y' AS "IsExists" FROM DUMMY;
ELSE 
	SELECT 'N' AS "IsExists" FROM DUMMY;
END IF;
END;







