
CALL APZ_EXISTSPROC('USP_APZ_MRP_IRS');

GO

CREATE PROCEDURE USP_APZ_MRP_IRS
(
	IN fdate date, tdate date,	-- Từ ngày, đến ngày
	MRPTYPE nvarchar(2),				-- MRP Type: 1,2,3,4
	Forecast nvarchar(1000) default '',		-- Forecast ID (1 hoặc nhiều)
	SalesOrderID nvarchar(4000),		-- Sales Order (1 hoặc nhiều)
	PrdSchedule nvarchar(1000),		-- Production Schedule
	Whs nvarchar(1000),				-- Các kho tính MRP
	MrpID int default 0,
	Project nvarchar(1000),			-- Project
	PeriodType char(1)			-- D/W: Day/Week
)
AS
BEGIN

	declare type char(1) = 'O';
	declare tmpdate date;
	declare overdue date;
	declare dateId int;	
	
	declare listitem nvarchar(40000) = '';
	
	declare NoDayJump int;
	declare MinDateIDX int;
	declare MaxDateIDX int;
	
	declare tmpIntervalDay date; 
	declare count int; 
	declare beginWeek date; 
	declare beginMonth date;
	
	if ifnull(:Forecast, '') <> '' then
		type = 'F';
	end if;
	
	CREATE LOCAL TEMPORARY TABLE #TBL_APZ_MRP(ID int GENERATED by default AS IDENTITY (start with 1 increment by 1),"ItmCode" nvarchar(50), "ItmName" nvarchar(300), "ItmType" char(1), "GrpID" int, "GrpName" nvarchar(300), "PrcMethod" nvarchar(1), "Pos" int, "Note" nvarchar(100), "LotSize" decimal(28,10), OB decimal(28,10), "DDate" date, "Amnt" decimal(28,10), "LeadTime" int, "ToleranceDay" int, "MinOrder" int, "DateId" int, "DateIDX" int, "isZero" int default 0, "IntervalID" int, "IntervalDate" date, "BPCode" nvarchar(50), "QLeadTime" int, "QRate" decimal(28,10), "BomVersion" nvarchar(100), "NoteType" char(1), "SourceNo" nvarchar(254), "DemandType" nvarchar(20), "DemandEntry" int, "DemandLine" int, "DemandDetailID" nvarchar(50), "FatherCode" nvarchar(50), "IDXinBlock" int,"DemandAmount" decimal(28,10), "DemandAccum" decimal(28,10), "TotalBlock" decimal(28,10), "FromDate" date, "ToDate" date,"FullCode" nvarchar(2000));
	
	-- Danh mục chỉ tiêu
	CREATE LOCAL TEMPORARY TABLE #TBL_MRPItem("Pos" int, "Note" nvarchar(100));
	insert into #TBL_MRPItem ("Pos","Note") Values(1000000,N'I. DEMAND (I.1+I.2+I.3+I.4)');
	insert into #TBL_MRPItem ("Pos","Note") Values(1100000,N'I.1. Forecast');
	insert into #TBL_MRPItem ("Pos","Note") Values(1200000,N'I.2. Sales Order');
	insert into #TBL_MRPItem ("Pos","Note") Values(1300000,N'I.3. Requirement from FatherCode');
	insert into #TBL_MRPItem ("Pos","Note") Values(1400000,N'I.4. Requirement from Production Schedule');
	insert into #TBL_MRPItem ("Pos","Note") Values(2000000,N'II. ISSUED PLANNED');
	insert into #TBL_MRPItem ("Pos","Note") Values(3000000,N'III. RECEIVED PLANNED');
	insert into #TBL_MRPItem ("Pos","Note") Values(4000000,N'IV. STOCK (PLAN)');
	insert into #TBL_MRPItem ("Pos","Note") Values(5000000,N'V. REQUIREMENT');
	insert into #TBL_MRPItem ("Pos","Note") Values(5100000,N'V.1. REQUIREMENT DETAIL');
	
	-- Danh mục ca ngày làm việc----------------------------------------------------------------------------------------------------------------
	create local temporary table #apz_WSH1 ("WorkDate" date, ID int, "Shift" nvarchar(10));
	insert into #apz_WSH1 ("WorkDate",ID,"Shift") 
	select "WorkDate",ID,max(iFnull("Shift",'')) 
	from apz_WSH1
	group by "WorkDate",ID;
	
	
	-- Danh mục ngày tháng-----------------------------------------------------------------------------------------------------------------------
	create local temporary table #tblDate ("DDate" date, "ReplaceDate" date, "DateId" int, "DateIDX" int, "FromDate" date, "ToDate" date, "Date_Index" int GENERATED by default AS IDENTITY (start with 1 increment by 1));
	-- Theo ngày
	if :PeriodType='D' then -- Theo ngay
		overdue = add_days(:fdate, -1);
		insert into #tblDate("DDate","DateId","DateIDX","FromDate","ToDate") values (:overdue,1,1,:overdue,:overdue);
		tmpdate = :fdate;
		dateId = 1;
		
		while :tmpdate <= :tdate do
		
			insert into #tblDate("DDate","DateId","FromDate","ToDate") values (:tmpdate,0,:tmpdate,:tmpdate);
			
			if (select count(1) from #apz_WSH1 where "Shift" <> '' and "WorkDate"=:tmpdate)>0 then
				dateId = :dateId + 1;
				update #tblDate set "DateId" = :dateId where "DDate"=:tmpdate;
			end if;
			
			update #tblDate set "DateIDX" = :dateId where "DDate"=:tmpdate;
			tmpdate = add_days(tmpdate, 1);
			
		end while;
	
	else if :PeriodType = 'W' then -- Theo tuan
		
		overdue = add_days(:fdate, -weekday(:fdate)); --ngay dau tuan (thu 2)
		overdue = add_days(:overdue, -7);
		tmpdate = :overdue;
		dateId = 1;
		
		while :tmpdate<=:tdate do
			insert into #tblDate("DDate","DateId","DateIDX","FromDate","ToDate") values (:tmpdate,:dateId,:dateId,:tmpdate,add_days(:tmpdate, 6));
			dateId = :dateId + 1;
			tmpdate = add_days(:tmpdate, 7);
		end	while;
	
	else if :PeriodType = 'M' then -- Theo thang

		overdue = add_months(:fdate, -1);
		tmpdate = :overdue;
		dateId=1;
		
		while :tmpdate<= :tdate do
			insert into #tblDate("DDate","DateId","DateIDX","FromDate","ToDate") values (:tmpdate,:dateId,:dateId,:tmpdate,add_days(add_months(:tmpdate, 1), -1));
			dateId = :dateId + 1;
			tmpdate = add_months(:tmpdate, 1);
		end while;
		
	else -- Theo nam
		
		overdue = add_years(:fdate, -1);
		tmpdate = :overdue;
		dateId=1;
		while :tmpdate<=:tdate do
		
			insert into #tblDate("DDate","DateId","DateIDX","FromDate","ToDate") values (:tmpdate,:dateId,:dateId,:tmpdate,add_days(add_years(:tmpdate, 1), -1));
			dateId = :dateId + 1;
			tmpdate = add_years(:tmpdate, 1);
		end while;
	
	end if;
	end if;		
	end if;
	
	update #tblDate set "ToDate"=:tdate where "ToDate">:tdate;
	
	-- Danh mục kho ----------------------------------------------------------------------------------------------------------------
	create local temporary table #OWHS("WHCode" nvarchar(8), "WHName" nvarchar(100));
	insert into #OWHS select "WhsCode", "WhsName" from OWHS where "WhsCode" in (select trim(Data) from Split(:Whs,','));

	-- Sales Order
	create local temporary table #listSOID (SOID int);
	
	if :MRPTYPE=1 then
		insert into #listSOID (SOID) select a."DocEntry" from ORDR a, RDR1 b where a."DocEntry"=b."DocEntry" and a.CANCELED='N' and b."ShipDate" between :fdate and :tdate;
	else if :MRPTYPE=2 then
		insert into #listSOID (SOID) select a."DocEntry" from ORDR a, RDR1 b where cast(a."DocNum" as nvarchar) not in (select trim(Data) from Split(:SalesOrderID,',')) and a."DocEntry"=b."DocEntry" and a.CANCELED='N' and b."ShipDate" between :fdate and :tdate;
	else if :MRPTYPE=4 then
		insert into #listSOID (SOID) select "DocEntry" from ORDR where cast("DocNum" as nvarchar) in (select trim(Data) from Split(:SalesOrderID,','));
	end if;
	end if;
	end if;
	
	
	create local temporary table #SO ("DocEntry" int, "LineNum" int, "ItemCode" nvarchar(50), "WhsCode" nvarchar(8), "OpenQty" decimal(21,6), "ShipDate" date);
	
	insert into #SO ("DocEntry", "LineNum", "ItemCode", "WhsCode", "OpenQty", "ShipDate")
	select b."DocEntry",b."LineNum",b."ItemCode",b."WhsCode",sum(b."OpenInvQty"), b."ShipDate"
	from ORDR a, RDR1 b 
	where a."DocEntry"=b."DocEntry" and a.CANCELED='N' and b."LineStatus"='O' and b."WhsCode" in (select "WHCode" from #OWHS) 
	and a."DocEntry" in (select SOID from #listSOID)
	and (b."Project"=:Project or :Project='')
	group by b."DocEntry",b."LineNum",b."ItemCode",b."WhsCode",b."ShipDate";
	
	
	-- Forecast
	create local temporary table #FO ("Code" int, "LineID" int,"ItemCode" nvarchar(50),"Date" date,"Qty" decimal(21,6),"DateId" int, "DateIDX" int);
	
	insert into #FO select "Code","LineID","ItemCode","Date",sum("Quantity"),0, 0 from APZ_FCT1 where "Date" between :fdate and :tdate and cast("Code" as nvarchar) in (select trim(Data) from Split(:Forecast,',')) and "WhsCode" in (select "WHCode" from #OWHS) group by "Code","LineID","ItemCode","Date","Code";

	update #FO set "DateId" = a."DateId", "DateIDX" = a."DateIDX" from #tblDate a, #FO where #FO."Date" between a."FromDate" and a."ToDate";
	
	
	-- Production Schedule
	create local temporary table #PS("PSId" int,"Line" int,"ItemCode" nvarchar(50), "WorkDay" date, "Qty" decimal(21,6), "DateId" int, "DateIDX" int);
	
	insert into #PS select b."PSId","Line",b."ItemCode", "WorkDay", sum("Qty"), 0, 0 
		from apz_OPRS a, apz_PRS1 b where a."PSCode"=b."PSId" and b."TypePlanning"=2 and :MRPTYPE=3 and cast(a."PSCode" as nvarchar) in (select trim(Data) from Split(:PrdSchedule,',')) group by b."PSId",b."ItemCode", "WorkDay","PSId","Line";
		
	update #PS set "DateId" = a."DateId", "DateIDX" = a."DateIDX" from #PS, #tblDate a where #PS."WorkDay" between a."FromDate" and a."ToDate";
	
	
	-- Danh mục BOM
	create local temporary table #OITT("Code" nvarchar(50), "Qauntity" decimal(21, 6));
	insert into #OITT select "Code", "Qauntity" from OITT;
	-- where TreeType<>'S'
	create local temporary table #ITT1 ("Father" nvarchar(20),"Code" nvarchar(20),"Quantity" decimal(21,6));
	insert into #ITT1 select a."Father",a."Code",a."Quantity"/b."Qauntity" from ITT1 a, #OITT b where a."Type"=4 and a."Father"=b."Code";
	
	
	-- Danh mục Item
	select string_agg(T0."ItemCode", ',') into listitem from (select "ItemCode" from #SO UNION ALL select "ItemCode" from #FO UNION All select "ItemCode" from #PS) T0;

	create local temporary table #OITM("CardCode" nvarchar(15),"ItemCode" nvarchar(20),"ItemName" nvarchar(100),"InvntItem" varchar(1),"ItmType" varchar(1),"LeadTime" int,"MinOrdrQty" decimal(21,6),"OrdrMulti" decimal(21,6),"PrcrmntMtd" varchar(1), "ToleranDay" int, "ItmsGrpCod" int, "ItmsGrpNam" nvarchar(100), "OrdrIntrvl" int,"ByWh" varchar(1),"MinLevel" decimal(21,6));
	
	insert into #OITM 
	select a."CardCode",a."ItemCode",a."ItemName",a."InvntItem", 'O',ifnull(a."LeadTime",0),a."MinOrdrQty",a."OrdrMulti",a."PrcrmntMtd", ifnull(a."ToleranDay",0), b."ItmsGrpCod", b."ItmsGrpNam", a."OrdrIntrvl",a."ByWh",a."MinLevel" 
	from OITM a, OITB b
	where /*InvntItem='Y' and*/ a."ItmsGrpCod"=b."ItmsGrpCod" and a."PlaningSys"='M'
	and "ItemCode" in (select "Code" from getComponentByFGs(:listitem));
	

	--==BEGIN PURCHASE QUOTA======================================================================================
	
	create local temporary table #QUOTA(ID int GENERATED by default AS IDENTITY (start with 1 increment by 1),"FromDate" date, "ToDate" date, "ItmCode" nvarchar(50), "BPCode" nvarchar(20), "Rate" decimal(28,10), "Total" decimal(28,10), "LeadTime" int default 0, "BPLeadTime" int, "QPos" int, "BPPrefer" char(1), "Ord" int, "PrcMethod" char(1) default 'B');
	-- Lấy những Item Có thiết lập Quota
	insert into #QUOTA ("FromDate","ToDate","ItmCode","BPCode","Rate","BPLeadTime", "QPos", "BPPrefer")
	select ifnull(b."FromDate",'2000-01-01'),ifnull(b."ToDate",cast('2099-12-31' as date)),ifnull(a."ItemCode",''),ifnull(c."CardCode",''),ifnull(c."Per",0),ifnull(c."LeadTime",0),5100000,'N' 
	from APZ_OIQA a, APZ_IQA1 b, APZ_IQA2 c
	where a."ItemCode"=b."ItemCode" and b."PeriodID"=c."PeriodID" and ifnull(c."Per",0)>0;
	
	
	-- Lấy những Item không thiết lập Quota
	insert into #QUOTA ("FromDate","ToDate","ItmCode","BPCode","Rate","BPLeadTime", "QPos", "BPPrefer")
	select '2000-01-01','2099-12-31',"ItemCode","CardCode",100,"LeadTime",5100000,'Y' from #OITM
	where "ItemCode" not in (select ifnull(a."ItemCode",'') from APZ_OIQA a, APZ_IQA1 b, APZ_IQA2 c where a."ItemCode"=b."ItemCode" and b."PeriodID"=c."PeriodID" and ifnull(c."Per",0)>0);
	
	
	update T1 set "Ord" = T0."Row"  from (select ID,"ItmCode","BPCode","FromDate","ToDate", ROW_NUMBER() OVER(PARTITION BY "ItmCode","FromDate","ToDate" ORDER BY "ItmCode","BPCode","FromDate","ToDate") AS "Row"  from #QUOTA) T0, #QUOTA T1  where T0.ID=T1.ID;
	-- Những Item=Make thì lấy theo LeadTime, Những Item=Buy thì lấy theo BPLeadTime
	update #QUOTA set "LeadTime" = 0 /*x.LeadTime*/, "PrcMethod" = x."PrcrmntMtd" from #QUOTA, #OITM x where x."ItemCode"=#QUOTA."ItmCode" and x."PrcrmntMtd"='M';


	if :PeriodType='W' then
		update #QUOTA set "LeadTime" = CEIL("LeadTime"/7), "BPLeadTime" = CEIL("BPLeadTime"/7);
		update #OITM set "LeadTime" = CEIL("LeadTime"/7), "ToleranDay" = CEIL("ToleranDay"/7);
	
	else if :PeriodType='M' then
		update #QUOTA set "LeadTime" = FLOOR("LeadTime"/30), "BPLeadTime" = FLOOR("BPLeadTime"/30);
		update #OITM set "LeadTime" = FLOOR("LeadTime"/30), "ToleranDay" = FLOOR("ToleranDay"/30);
	
	else if :PeriodType='Y' then

		update #QUOTA set "LeadTime" = FLOOR("LeadTime"/365), "BPLeadTime" = FLOOR("BPLeadTime"/365);
		update #OITM set "LeadTime" = FLOOR("LeadTime"/365), "ToleranDay" = FLOOR("ToleranDay"/365);
	end	if;
	end if;
	end if;
	
	--==END PURCHASE QUOTA========================================================================================================================================================
	-- ===========================================================================================================================================================================
	--==BEGIN BOM VERSION-==============================================================================
	
	create local temporary table #BOM_APZ ("Type" char(1), "Father" nvarchar(50), "Version" nvarchar(55), "FromDate" date, "ToDate" date, "Code" nvarchar(50), "Qty" decimal(21,6));
	insert into #BOM_APZ ("Type", "Father", "Version", "FromDate", "ToDate", "Code", "Qty")
	select a."Type",a."Code",a."Version",ifnull(cast(a."ActFrom" as date),:fdate),ifnull(cast(a."ActTo" as date),:tdate),b."Code",sum(cast(b."Quantity" as decimal(28,10))/cast(a."Qauntity" as decimal(28,10))) from APZ_OITT a, APZ_ITT1 b where a."BomVerID"=b."Father" group by a."Type",a."Code",a."Version",b."Code",a."ActFrom",a."ActTo";
	
	if :PeriodType='W' then
		tmpdate = add_days(:fdate, -weekday(:fdate));
	else 
		tmpdate = :fdate;
	end if;
	
	CREATE LOCAL TEMPORARY TABLE #BOM_M ("ItmCode" nvarchar(50), "BDate" date, "BVersion" nvarchar(100), "BType" nvarchar(20));
	
	insert INTO #BOM_M ("ItmCode", "BDate")
	select a."ItemCode",b."Date" from #OITM a, 
	(SELECT add_days(:tmpdate, element_number) "Date"
	FROM SERIES_GENERATE_INTEGER(1,1,1000)
	WHERE add_days(:tmpdate, element_number) <= :tdate) b
	where a."ItemCode" in (select "Code" from #OITT)
	or a."ItemCode" in (select "Father" from #BOM_APZ);
	
	-- BOM Special
	update #BOM_M set "BVersion" = x."Version", "BType" = 'Special' from #BOM_M, #BOM_APZ x where x."Father"="ItmCode" and "BDate" between x."FromDate" and x."ToDate" and x."Type"='S';
	-- BOM Normal
	update #BOM_M set "BVersion" = (select max(x."Version") from #BOM_APZ x where x."Father"="ItmCode" and "BDate" between x."FromDate" and x."ToDate" and x."Type"='N')
	where "BVersion" is null;
	update #BOM_M set "BType" = 'Normal' where "BVersion" is not null and "BType" is null;
	update #BOM_M set "BVersion"=ifnull("BVersion",''), "BType" = ifnull("BType",'');
			
	-- BOM chi tiết
	CREATE LOCAL TEMPORARY TABLE #BOM_D ("Father" nvarchar(50), "BDate" date, "BVersion" nvarchar(100), "BType" nvarchar(20),
							"Code" nvarchar(50), "Quantity" decimal(28,10));
	
	-- BOM APZON
	insert INTO #BOM_D("Father","BDate","BVersion","BType","Code","Quantity")
	select a."ItmCode",a."BDate",a."BVersion",a."BType",b."Code",b."Qty" from #BOM_M a, #BOM_APZ b where a."BVersion"<>'' and a."ItmCode"=b."Father" and a."BVersion"=b."Version";
	-- BOM SAP
	insert into #BOM_D("Father","BDate","BVersion","BType","Code","Quantity")
	select a."ItmCode",a."BDate",a."BVersion",a."BType",b."Code",b."Quantity" from #BOM_M a, #ITT1 b where a."BVersion"='' and a."ItmCode"=b."Father";

	-- ===========================================================================================================================================================================
	-- ===========================================================================================================================================================================
	-- Xác định ItmType (xác định theo BOM): F-Finish Goods, S-Semi Goods, R-Raw Material, O-Other
	update #OITM set "ItmType"='F' where "ItemCode" in (select "Code" from #OITT) and "ItemCode" not in (select "Code" from #ITT1);
	update #OITM set "ItmType"='S' where "ItemCode" in (select "Code" from #OITT) and "ItemCode" in (select "Code" from #ITT1);
	update #OITM set "ItmType"='R' where "ItemCode" not in (select "Code" from #OITT) and "ItemCode" in (select "Code" from #ITT1);
	-- Bảng chứa các mã CHA
	create local temporary table #tblFather	("Fcode" nvarchar(50), "DemandType" nvarchar(20), "DemandEntry" int, "DemandLine" int, "DetailID" nvarchar(50), "FatherCode" nvarchar(50), "FullCode" nvarchar(2000));
	-- Bảng chứa các mã CON
	create local temporary table #tblSub ("Scode" nvarchar(50), "DemandType" nvarchar(20), "DemandEntry" int, "DemandLine" int, "DetailID" nvarchar(50), "FatherCode" nvarchar(50));
	-- Bảng chứa tất cả các mã tính toán theo đợt

	CREATE LOCAL TEMPORARY TABLE #tbltmp(
			IDX int GENERATED by default AS IDENTITY (start with 1 increment by 1),
            "ItmCode" NVARCHAR(50),
			"BPCode" NVARCHAR(50),
            "Pos" INT, "PosDetailID" nvarchar(100),
            "Note" NVARCHAR(100) ,
            "DDate" DATE ,
            "LeadTime" INT , "ToleranDay" int,
            "Amnt" DECIMAL(28, 10) ,
            OB DECIMAL(28, 10) ,
            "ReplaceDate" DATE,
            "isBOM" CHAR(1) DEFAULT 'N',
			"DateId" int, "DateIDX" int,
			"QLeadTime" int,
			"QRate" DECIMAL(28,10),
			"SourceNo" nvarchar(4000), "DemandType" nvarchar(20), "DemandEntry" int, "DemandLine" int, "DemandAmount" DECIMAL(28,10), "DemandAccum" DECIMAL(28,10), "DemandDetailID" nvarchar(50),
			"FatherCode" nvarchar(50), 
			"IDXinBlock" int, "TotalBlock" DECIMAL(28,10),"TotalRequirement" DECIMAL(28,10),
			"FromDate" date, "ToDate" date, "Date_Index" int,
			"FullCode" nvarchar(2000)
        );
        
        
        -- DANH MỤC OPEN DOCUMENT--------------------------------------------------------------------------------------------------------------------
	-- Tồn kho thực tế
	create local temporary table #OINM("ItemCode" nvarchar(20), "DocDate" date, "Qty" decimal(21, 6), "Sig" int);
	insert into #OINM
	select a."ItemCode",a."DocDate",SUM(a."InQty"-a."OutQty"), 1 from OINM a where a."Warehouse" in (select "WHCode" from #OWHS) and (a."PrjCode"=:Project or :Project='') group by a."ItemCode",a."DocDate" having sum(a."InQty"-a."OutQty")<>0;
	-- Chưa nhập kho từ lệnh sản xuất
	create local temporary table #OWOR("ItemCode" nvarchar(20), "DueDate" date, "OpnQty" decimal(21,6), "Sig" int);
	insert into #OWOR
	select "ItemCode","DueDate",sum(a."PlannedQty"-a."CmpltQty"), 1 from OWOR a where a."Type"='S' and a."Status" in ('R', 'P') and a."DueDate" <= :tdate and a."PlannedQty">a."CmpltQty" and a."Warehouse" in (select "WHCode" from #OWHS) and (a."Project"=:Project or :Project='') group by "ItemCode","DueDate",a."DocEntry" having sum(a."PlannedQty"-a."CmpltQty")<>0;
	-- Chưa xuất kho cho lệnh sản xuất
	create local temporary table #WOR1("ItemCode" nvarchar(20), "DueDate" date, "StartDate" date, "OpnQty" decimal(21,6), "Sig" int);
	insert into #WOR1
	select b."ItemCode",a."DueDate",b."StartDate",sum(b."PlannedQty"-b."IssuedQty"), -1 from OWOR a, WOR1 b where a."DocEntry"=b."DocEntry" and a."Type"='S' and a."Status" in ('R', 'P') and b."StartDate" <= :tdate and b."PlannedQty">b."IssuedQty" and b."wareHouse" in (select "WHCode" from #OWHS) and (a."Project"=:Project or :Project='') group by b."ItemCode","DueDate",b."StartDate",b."DocEntry",b."LineNum" having sum(b."PlannedQty"-b."IssuedQty")<>0;
	-- Chưa nhập kho từ PO mua hàng
	create local temporary table #POR1 ("ItemCode" nvarchar(20), "ShipDate" date, "OpnQty" decimal(21,6), "Sig" int);
	insert into #POR1
	select b."ItemCode",b."ShipDate",sum(b."OpenInvQty"), 1 from OPOR a, POR1 b where a."DocEntry"=b."DocEntry" and a.CANCELED='N' and a."DocStatus"='O' and b."LineStatus"='O' and b."ShipDate" <= :tdate and b."WhsCode" in (select "WHCode" from #OWHS) and (b."Project"=:Project or :Project='') group by b."ItemCode",b."ShipDate",a."ObjType",b."DocEntry",b."LineNum" having sum(b."OpenQty")<>0;
	-- Chưa xuất kho cho SO bán hàng
	create local temporary table #RDR1 ("DocEntry" int, "LineNum" int, "ItemCode" nvarchar(20), "ShipDate" date, "OpnQty" decimal(21,6), "Sig" int, "DateId" int, "DateIDX" int);
	insert into #RDR1
	select a."DocEntry",b."LineNum",b."ItemCode",b."ShipDate",sum(b."OpenInvQty"), -1, 0, cast(0 as int) from ORDR a, RDR1 b where a."DocEntry"=b."DocEntry" and a."DocEntry" in (select SOID from #listSOID) and a.CANCELED='N' and a."DocStatus"='O' and b."LineStatus"='O' and b."ShipDate" <= :tdate and b."WhsCode" in (select "WHCode" from #OWHS) and (b."Project"=:Project or :Project='') group by a."ObjType",a."DocEntry",b."ItemCode",b."ShipDate",b."DocEntry",b."LineNum" having sum(b."OpenQty")<>0;
	create local temporary table #SO_OPEN ("ItemCode" nvarchar(20), "ShipDate" date, "OpnQty" decimal(21, 6), "Sig" int, "DateId" int);
	insert into #SO_OPEN
